// Writes static/icons.svg, one sprite of <symbol id="i-NAME"> elements, and static/icons.COPYING, and copies the
// Bingux app icons (apps/<app>/bingux-<app>.svg in the Bingux repository) to static/bingux/ for the Bingux page.
//
// UI icons come from the Bingux icon set (crates/ui/icons in the Bingux repository: Phosphor, chat-icon fork, MIT).
// The few with no Bingux equivalent are drawn here on a 24 x 24 grid with a round 1.6 px stroke. Distribution and
// GitHub marks are Simple Icons glyphs (CC0) from scripts/simple-icons.json.
//
// The sprite and the licence are committed, so a site build never needs the Bingux sources. Re-run this script
// (`yarn icons`) after changing the lists below. BINGUX_MAIN points at a Bingux checkout (default ~/dev/bingux-main).
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const site = fileURLToPath(new URL("..", import.meta.url));
const binguxMain = process.env.BINGUX_MAIN ?? path.join(homedir(), "dev/bingux-main");
const iconDir = path.join(binguxMain, "crates/ui/icons");

/** Site icon name -> Bingux symbolic icon file (without -symbolic.svg). */
const BINGUX = {
    search: "system-search",
    copy: "edit-copy",
    check: "object-select",
    "arrow-right": "go-next",
    "arrow-left": "go-previous",
    "chevron-right": "go-next",
    sun: "weather-clear",
    moon: "weather-clear-night",
    menu: "open-menu",
    x: "window-close",
    note: "dialog-information",
    tip: "help-about",
    warning: "dialog-warning",
    danger: "dialog-error",
    edit: "document-edit",
    terminal: "utilities-terminal",
    page: "text-x-generic",
    monitor: "video-display",
    plus: "list-add",
    code: "text-x-script",
};

/** Hand-drawn icons for names the Bingux set has no equivalent for. */
const DRAWN = {
    hash: '<path d="M9.5 4 8 20M16 4l-1.5 16M4.5 9h15M4 15h15"/>',
    enter: '<path d="M19 5v6.5a1.5 1.5 0 0 1-1.5 1.5H5"/><path d="M9 9 5 13l4 4"/>',
    "arrow-out": '<path d="M7 17 17 7"/><path d="M9 7h8v8"/>',
    "chevron-down": '<path d="m6 9.5 6 6 6-6"/>',
    "arrow-up": '<path d="M12 19V5M6.5 10.5 12 5l5.5 5.5"/>',
    "arrow-down": '<path d="M12 5v14M6.5 13.5 12 19l5.5-5.5"/>',
};

const LOGOS = JSON.parse(readFileSync(path.join(site, "scripts/simple-icons.json"), "utf8"));

const symbols = [];
for (const [name, file] of Object.entries(BINGUX)) {
    const src = readFileSync(path.join(iconDir, `${file}-symbolic.svg`), "utf8");
    const viewBox = src.match(/viewBox="([^"]+)"/)?.[1] ?? "0 0 16 16";
    const inner = src
        .replace(/^[\s\S]*?<svg[^>]*>/, "")
        .replace(/<\/svg>\s*$/, "")
        .replace(/\s*fill="#[0-9a-fA-F]{3,8}"/g, "")
        .replace(/\n\s*/g, "")
        .trim();
    symbols.push(`<symbol id="i-${name}" viewBox="${viewBox}">${inner}</symbol>`);
}
for (const [name, body] of Object.entries(DRAWN)) {
    symbols.push(
        `<symbol id="i-${name}" viewBox="0 0 24 24"><g fill="none" stroke="currentColor" stroke-width="1.6" ` +
            `stroke-linecap="round" stroke-linejoin="round">${body}</g></symbol>`,
    );
}
for (const [name, body] of Object.entries(LOGOS)) {
    symbols.push(`<symbol id="i-${name}" viewBox="0 0 24 24">${body.replace(/\s*fill="currentColor"/g, "")}</symbol>`);
}

const header =
    "<!-- Generated by scripts/build-icons.mjs. UI icons: Bingux icon set (Phosphor, MIT, see icons.COPYING). " +
    "Distribution and GitHub marks: Simple Icons (CC0); the marks are trademarks of their owners. -->";
writeFileSync(
    path.join(site, "static/icons.svg"),
    `${header}\n<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join("\n")}\n</svg>\n`,
);
writeFileSync(path.join(site, "static/icons.COPYING"), readFileSync(path.join(iconDir, "COPYING"), "utf8"));
mkdirSync(path.join(site, "static/bingux"), { recursive: true });
for (const app of ["settings", "files", "taxonomy"]) {
    copyFileSync(path.join(binguxMain, "apps", app, `bingux-${app}.svg`), path.join(site, `static/bingux/${app}.svg`));
}
console.log(`wrote ${symbols.length} symbols to static/icons.svg and the Bingux app icons to static/bingux/`);
