//! Render a schema catalog as TypeScript declarations.
//!
//! The output is a pure function of the catalog: no clock, no environment, no iteration
//! over an unordered map, so the same schema is the same bytes on every machine and the
//! checked-in golden can be compared byte for byte.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use gnoblin_schema::{Catalog, DefaultValue, Field, Method, Namespace, ObjectType, Property, Signal, Type};

/// The hand-written half: the proposed stock library, declared as `module "gnoblin"`.
const STOCK_DTS: &str = include_str!("../static/gnoblin-stock.d.ts");

/// The module every generated module imports its shared types from.
const SHARED_MODULE: &str = "gnoblin/schema";

/// Words a parameter or a signal field cannot be named in TypeScript.
const RESERVED: &[&str] = &[
    "await",
    "break",
    "case",
    "catch",
    "class",
    "const",
    "continue",
    "debugger",
    "default",
    "delete",
    "do",
    "else",
    "enum",
    "export",
    "extends",
    "false",
    "finally",
    "for",
    "function",
    "if",
    "implements",
    "import",
    "in",
    "instanceof",
    "interface",
    "let",
    "new",
    "null",
    "package",
    "private",
    "protected",
    "public",
    "return",
    "static",
    "super",
    "switch",
    "this",
    "throw",
    "true",
    "try",
    "typeof",
    "var",
    "void",
    "while",
    "with",
    "yield",
];

/// The first parameter of every signal handler: the object the signal came from.
const TARGET: &str = "target";

/// Render `catalog` as one declaration file: a generated module per schema namespace,
/// then the proposed stock library.
///
/// The catalog is read as it is. A caller that must not expose an owner-only namespace
/// passes a catalog loaded without it.
#[must_use]
pub fn render_dts(catalog: &Catalog) -> String {
    let namespaces = catalog.namespaces();
    let mut out = String::new();
    write_header(&mut out, catalog, &namespaces);
    write_shared_module(&mut out);
    for namespace in &namespaces {
        out.push('\n');
        write_namespace(&mut out, catalog, namespace);
    }
    out.push('\n');
    write_signal_events(&mut out, catalog, &namespaces);
    out.push('\n');
    out.push_str(STOCK_DTS);
    out
}

/// `gnoblin/schema/signals`: every schema signal by its `namespace.object.signal` name, with the event
/// `gnoblin.on` hands a handler. The runtime builds that event from the compositor's signal: its name, the identity
/// of the object that raised it, and each field under its camelCase name.
fn write_signal_events(out: &mut String, catalog: &Catalog, namespaces: &[Namespace]) {
    let _ = writeln!(out, "declare module \"{SHARED_MODULE}/signals\" {{");
    out.push_str("    /** Every schema signal, by the name `gnoblin.on` takes, and the event its handler receives. */\n");
    out.push_str("    export interface GnoblinSignals {\n");
    for namespace in namespaces {
        for object in catalog.objects(namespace) {
            for signal in &object.signals {
                let name = format!("{namespace}.{}.{}", object.name, signal.name);
                let mut members = format!(
                    "readonly name: {}; readonly object: number;",
                    string_literal(&name)
                );
                for field in &signal.fields {
                    let _ = write!(
                        members,
                        " readonly {}: {};",
                        param_ident(&field.name, &["name", "object"]),
                        event_type(&field.ty)
                    );
                }
                let _ = writeln!(out, "        {}: {{ {members} }};", string_literal(&name));
            }
        }
    }
    out.push_str("    }\n");
    out.push_str("}\n");
}

/// A schema type as the event carries it: an identity is the object's number.
fn event_type(ty: &Type) -> String {
    match ty {
        Type::Bool => "boolean".to_owned(),
        Type::Int | Type::Uint | Type::Double | Type::ObjectRef(_) => "number".to_owned(),
        Type::Text => "string".to_owned(),
        Type::Bytes => "number[]".to_owned(),
        Type::List(inner) => format!("{}[]", event_type(inner)),
    }
}

fn write_header(out: &mut String, catalog: &Catalog, namespaces: &[Namespace]) {
    out.push_str("// gnoblin.d.ts: the types of the Gnoblin JavaScript and TypeScript API.\n");
    out.push_str("//\n");
    out.push_str("// Generated by crates/gnoblin-js-types from the object schema (crates/gnoblin-schema),\n");
    out.push_str("// then followed by the hand-written stock library. Do not edit: declare a member in the\n");
    out.push_str("// schema and regenerate, or write the file again with `ensure_user_files`.\n");
    out.push_str("//\n");
    let versions: Vec<String> = namespaces
        .iter()
        .filter_map(|namespace| {
            catalog
                .version(namespace)
                .map(|version| format!("{namespace} {version}"))
        })
        .collect();
    let _ = writeln!(out, "// Schema: {}.", versions.join(", "));
    out.push_str("//\n");
    out.push_str("// Part 1, the generated modules `gnoblin/schema/<namespace>`: one per schema namespace.\n");
    out.push_str("//   - One interface per schema object, named in PascalCase. A subclass extends its base\n");
    out.push_str("//     and declares only the members its base does not.\n");
    out.push_str("//   - Members are camelCase: schema `app_id` is `appId`. A doc comment names the schema\n");
    out.push_str("//     name when it differs, and carries the default, `Animatable.`, `Secret.` and `Since`.\n");
    out.push_str("//   - Schema value kinds: bool is boolean; int, uint and double are number; string is\n");
    out.push_str("//     string; bytes is Uint8Array; list<T> is T[]; an object reference is the object's\n");
    out.push_str("//     interface, or `| null` for an identity that may be nil. A record is a value and\n");
    out.push_str("//     never null. A namespace's error codes are the string-literal union `ErrorCode`.\n");
    out.push_str("//   - A property the schema marks readonly is `readonly`.\n");
    out.push_str("//   - A method takes typed parameters and returns `Reply`: the schema declares no method\n");
    out.push_str("//     results, so the promise settles when the compositor answers and carries no type.\n");
    out.push_str("//     A namespace function (`function = true`) is a member of an exported constant.\n");
    out.push_str("//   - SIGNALS: one shape everywhere. A signal `mode_changed` is the method\n");
    out.push_str("//     `onModeChanged(handler)`, where the handler receives the object the signal came\n");
    out.push_str("//     from, then the signal's fields as positional arguments in schema order, and\n");
    out.push_str("//     the method returns an `Unsubscribe` function. There are no event-name strings.\n");
    out.push_str("//\n");
    out.push_str("// Part 2, `module \"gnoblin\"`: the stock library. PROPOSED API: hand-written from\n");
    out.push_str("// design/js-research/owner-spec.md and spec-review.md, and not yet implemented.\n\n");
}

fn write_shared_module(out: &mut String) {
    let _ = writeln!(out, "declare module \"{SHARED_MODULE}\" {{");
    out.push_str("    /** Stops a subscription made by an `on<Signal>` method. Calling it twice is harmless. */\n");
    out.push_str("    export type Unsubscribe = () => void;\n");
    out.push_str("    /** The settlement of a method call. The schema declares no results, so there is no type. */\n");
    out.push_str("    export type Reply = Promise<unknown>;\n");
    out.push_str("}\n");
}

fn write_namespace(out: &mut String, catalog: &Catalog, namespace: &Namespace) {
    let objects: Vec<&ObjectType> = catalog.objects(namespace).collect();
    let by_name: BTreeMap<&str, &ObjectType> = objects.iter().map(|object| (object.name.as_str(), *object)).collect();

    let _ = writeln!(out, "declare module \"{SHARED_MODULE}/{namespace}\" {{");
    let _ = writeln!(
        out,
        "    import type {{ Reply, Unsubscribe }} from \"{SHARED_MODULE}\";"
    );

    let errors: Vec<&str> = catalog.errors(namespace).map(|error| error.name.as_str()).collect();
    if !errors.is_empty() {
        out.push('\n');
        out.push_str("    /** The error codes this namespace declares. */\n");
        out.push_str("    export type ErrorCode =\n");
        for (index, code) in errors.iter().enumerate() {
            let end = if index + 1 == errors.len() { ";" } else { "" };
            let _ = writeln!(out, "        | {}{end}", string_literal(code));
        }
    }

    for object in &objects {
        out.push('\n');
        write_object(out, namespace, object, &by_name);
    }
    out.push_str("}\n");
}

fn write_object(out: &mut String, namespace: &Namespace, object: &ObjectType, objects: &BTreeMap<&str, &ObjectType>) {
    let base = object.base.as_deref().and_then(|name| objects.get(name).copied());
    let mut doc = if object.record {
        format!(
            "Schema record `{namespace}.{}` (since {}): a value, not an identity.",
            object.name, object.since
        )
    } else {
        format!("Schema object `{namespace}.{}` (since {}).", object.name, object.since)
    };
    if object.secret {
        doc.push_str(" Secret.");
    }
    let _ = writeln!(out, "    /** {doc} */");
    let extends = match &object.base {
        Some(base) => format!(" extends {}", pascal(base)),
        None => String::new(),
    };

    let properties: Vec<&Property> = object
        .properties
        .iter()
        .filter(|property| !inherited_property(base, property))
        .collect();
    let methods: Vec<&Method> = object
        .methods
        .iter()
        .filter(|method| {
            !method.function
                && !base.is_some_and(|base| base.methods.iter().any(|inherited| inherited.name == method.name))
        })
        .collect();
    let signals: Vec<&Signal> = object
        .signals
        .iter()
        .filter(|signal| !base.is_some_and(|base| base.signals.iter().any(|inherited| inherited.name == signal.name)))
        .collect();

    if properties.is_empty() && methods.is_empty() && signals.is_empty() {
        let _ = writeln!(out, "    export interface {}{extends} {{}}", pascal(&object.name));
    } else {
        let _ = writeln!(out, "    export interface {}{extends} {{", pascal(&object.name));
        for property in properties {
            write_property(out, object, property, objects);
        }
        for method in methods {
            write_method(out, object, method, objects);
        }
        for signal in signals {
            write_signal(out, object, signal, objects);
        }
        out.push_str("    }\n");
    }

    let functions: Vec<&Method> = object.methods.iter().filter(|method| method.function).collect();
    if !functions.is_empty() {
        let _ = writeln!(
            out,
            "    /** The namespace functions of `{namespace}.{}`. */",
            object.name
        );
        let _ = writeln!(out, "    export const {}: {{", camel(&object.name));
        for method in functions {
            write_member_doc(out, &method_doc(object, method), "        ");
            let _ = writeln!(out, "        {};", method_signature(method, objects));
        }
        out.push_str("    };\n");
    }
}

/// Whether the base already declares `property` exactly, so the subclass inherits it.
fn inherited_property(base: Option<&ObjectType>, property: &Property) -> bool {
    base.is_some_and(|base| {
        base.properties.iter().any(|inherited| {
            inherited.name == property.name
                && inherited.ty == property.ty
                && inherited.readonly == property.readonly
                && inherited.default == property.default
                && inherited.animated == property.animated
        })
    })
}

fn write_property(out: &mut String, object: &ObjectType, property: &Property, objects: &BTreeMap<&str, &ObjectType>) {
    let mut parts = Vec::new();
    if camel(&property.name) != property.name {
        parts.push(format!("Schema name `{}`.", property.name));
    }
    if let Some(default) = &property.default {
        parts.push(format!("Default `{}`.", default_literal(default)));
    }
    if property.animated {
        parts.push("Animatable.".to_owned());
    }
    if property.secret {
        parts.push("Secret.".to_owned());
    }
    if property.since != object.since {
        parts.push(format!("Since {}.", property.since));
    }
    write_member_doc(out, &parts.join(" "), "        ");
    let readonly = if property.readonly { "readonly " } else { "" };
    let _ = writeln!(
        out,
        "        {readonly}{}: {};",
        camel(&property.name),
        ts_type(&property.ty, objects)
    );
}

fn write_method(out: &mut String, object: &ObjectType, method: &Method, objects: &BTreeMap<&str, &ObjectType>) {
    write_member_doc(out, &method_doc(object, method), "        ");
    let _ = writeln!(out, "        {};", method_signature(method, objects));
}

fn method_doc(object: &ObjectType, method: &Method) -> String {
    let mut parts = Vec::new();
    if camel(&method.name) != method.name {
        parts.push(format!("Schema name `{}`.", method.name));
    }
    if method.secret {
        parts.push("Secret.".to_owned());
    }
    let secret_params: Vec<String> = method
        .params
        .iter()
        .filter(|param| param.secret)
        .map(|param| format!("`{}`", param_ident(&param.name, &[])))
        .collect();
    if !secret_params.is_empty() {
        parts.push(format!("Secret parameters: {}.", secret_params.join(", ")));
    }
    if method.since != object.since {
        parts.push(format!("Since {}.", method.since));
    }
    parts.join(" ")
}

fn method_signature(method: &Method, objects: &BTreeMap<&str, &ObjectType>) -> String {
    format!(
        "{}({}): Reply",
        camel(&method.name),
        param_list(&method.params, objects, &[])
    )
}

fn write_signal(out: &mut String, object: &ObjectType, signal: &Signal, objects: &BTreeMap<&str, &ObjectType>) {
    let mut parts = vec![format!("Signal `{}`.", signal.name)];
    if signal.secret {
        parts.push("Secret.".to_owned());
    }
    if signal.since != object.since {
        parts.push(format!("Since {}.", signal.since));
    }
    write_member_doc(out, &parts.join(" "), "        ");

    // The handler's first parameter must not collide with a field of the signal.
    let mut target = TARGET.to_owned();
    while signal
        .fields
        .iter()
        .any(|field| param_ident(&field.name, &[]) == target)
    {
        target.push('_');
    }
    let mut params = format!("{target}: this");
    let fields = param_list(&signal.fields, objects, &[&target]);
    if !fields.is_empty() {
        params.push_str(", ");
        params.push_str(&fields);
    }
    let _ = writeln!(
        out,
        "        on{}(handler: ({params}) => void): Unsubscribe;",
        pascal(&signal.name)
    );
}

/// `name: type, ...` for a method's parameters or a signal's fields.
fn param_list(fields: &[Field], objects: &BTreeMap<&str, &ObjectType>, taken: &[&str]) -> String {
    fields
        .iter()
        .map(|field| format!("{}: {}", param_ident(&field.name, taken), ts_type(&field.ty, objects)))
        .collect::<Vec<_>>()
        .join(", ")
}

fn write_member_doc(out: &mut String, text: &str, indent: &str) {
    if !text.is_empty() {
        let _ = writeln!(out, "{indent}/** {text} */");
    }
}

/// One schema type as TypeScript spells it.
fn ts_type(ty: &Type, objects: &BTreeMap<&str, &ObjectType>) -> String {
    match ty {
        Type::ObjectRef(name) if objects.get(name.as_str()).is_none_or(|object| !object.record) => {
            format!("{} | null", pascal(name))
        }
        other => ts_element(other),
    }
}

/// A type with no `| null`: the element of a list never is nil, and a record is a value.
fn ts_element(ty: &Type) -> String {
    match ty {
        Type::Bool => "boolean".to_owned(),
        Type::Int | Type::Uint | Type::Double => "number".to_owned(),
        Type::Text => "string".to_owned(),
        Type::Bytes => "Uint8Array".to_owned(),
        Type::ObjectRef(name) => pascal(name),
        Type::List(inner) => format!("{}[]", ts_element(inner)),
    }
}

fn default_literal(default: &DefaultValue) -> String {
    match default {
        DefaultValue::Bool(value) => value.to_string(),
        DefaultValue::Int(value) => value.to_string(),
        DefaultValue::Uint(value) => value.to_string(),
        DefaultValue::Double(value) => number_literal(*value),
        DefaultValue::Text(value) => string_literal(value),
        DefaultValue::List(items) => {
            let items: Vec<String> = items.iter().map(default_literal).collect();
            format!("[{}]", items.join(", "))
        }
    }
}

/// A double without a trailing `.0`, which is how a person writes it in TypeScript.
fn number_literal(value: f64) -> String {
    if value.is_finite() && value.fract() == 0.0 && value.abs() < 1e15 {
        format!("{value:.0}")
    } else {
        value.to_string()
    }
}

/// A double-quoted literal in ASCII: the generated file stays ASCII whatever a default holds.
fn string_literal(text: &str) -> String {
    let mut literal = String::from("\"");
    for character in text.chars() {
        match character {
            '"' => literal.push_str("\\\""),
            '\\' => literal.push_str("\\\\"),
            '\n' => literal.push_str("\\n"),
            '\r' => literal.push_str("\\r"),
            '\t' => literal.push_str("\\t"),
            ' '..='~' => literal.push(character),
            other => {
                let mut units = [0u16; 2];
                for unit in other.encode_utf16(&mut units) {
                    let _ = write!(literal, "\\u{unit:04x}");
                }
            }
        }
    }
    literal.push('"');
    literal
}

/// `snake_case` as `camelCase`.
fn camel(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut upper = false;
    for character in name.chars() {
        if character == '_' || character == '-' {
            upper = true;
        } else if upper {
            out.extend(character.to_uppercase());
            upper = false;
        } else {
            out.push(character);
        }
    }
    out
}

/// `snake_case` as `PascalCase`.
fn pascal(name: &str) -> String {
    let camel = camel(name);
    let mut characters = camel.chars();
    match characters.next() {
        Some(first) => first.to_uppercase().chain(characters).collect(),
        None => String::new(),
    }
}

/// A schema name as a parameter name: camelCase, and never a reserved word or a name in `taken`.
fn param_ident(name: &str, taken: &[&str]) -> String {
    let mut ident = camel(name);
    while RESERVED.contains(&ident.as_str()) || taken.contains(&ident.as_str()) {
        ident.push('_');
    }
    ident
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_are_camel_and_pascal_case() {
        assert_eq!(camel("app_id"), "appId");
        assert_eq!(camel("x"), "x");
        assert_eq!(pascal("snapshot_node"), "SnapshotNode");
        assert_eq!(pascal("tree"), "Tree");
    }

    #[test]
    fn a_reserved_word_or_a_taken_name_gets_an_underscore() {
        assert_eq!(param_ident("default", &[]), "default_");
        assert_eq!(param_ident("class", &[]), "class_");
        assert_eq!(param_ident("target", &["target"]), "target_");
        assert_eq!(param_ident("value", &[]), "value");
    }

    #[test]
    fn a_double_has_no_trailing_zero_fraction() {
        assert_eq!(number_literal(1.0), "1");
        assert_eq!(number_literal(0.5), "0.5");
        assert_eq!(number_literal(-2.0), "-2");
    }

    #[test]
    fn a_string_literal_is_escaped_and_ascii() {
        assert_eq!(string_literal("a\"b\\c\n"), "\"a\\\"b\\\\c\\n\"");
        assert_eq!(string_literal("caf\u{e9}"), "\"caf\\u00e9\"");
        assert_eq!(string_literal("\u{1f600}"), "\"\\ud83d\\ude00\"");
    }
}
