/// Install the `gnoblin` global into a fresh Lua state.
pub(super) fn install<T: Transport + 'static>(
    lua: &Lua,
    shared: Rc<RefCell<Shared<T>>>,
    guard: Rc<Guard>,
    limits: Limits,
) -> mlua::Result<()> {
    lua.set_named_registry_value(CALLBACKS, lua.create_table()?)?;
    lua.set_named_registry_value(MODULES, lua.create_table()?)?;
    lua.set_named_registry_value(INSTANCES, lua.create_table()?)?;
    lua.set_named_registry_value(IDENTITIES, lua.create_table()?)?;

    let gnoblin = lua.create_table()?;

    {
        let shared = Rc::clone(&shared);
        gnoblin.set(
            "configure",
            lua.create_function(move |_, settings: Table| crate::configure::declare(&shared, &settings))?,
        )?;
    }
    {
        let shared = Rc::clone(&shared);
        gnoblin.set(
            "window_rule",
            lua.create_function(move |_, rule: Table| crate::configure::append_rule(&shared, &rule))?,
        )?;
    }
    {
        let shared = Rc::clone(&shared);
        let guard = Rc::clone(&guard);
        gnoblin.set(
            "load",
            lua.create_function(move |lua, pattern: String| {
                crate::host::load_pattern(lua, &shared, &guard, &limits, &pattern)
            })?,
        )?;
    }

    let timers = lua.create_table()?;
    {
        let shared = Rc::clone(&shared);
        timers.set(
            "after",
            lua.create_function(move |lua, (seconds, callback): (f64, Function)| {
                // The Lua surface counts seconds; the clock counts milliseconds. A
                // non-finite or out-of-range delay is refused here, not clamped, so a
                // typo in a config fails at load instead of firing at the wrong time.
                if !seconds.is_finite() || !(0.0..=MAX_TIMER_SECONDS).contains(&seconds) {
                    return Err(Error::runtime(format!(
                        "gnoblin.timers.after takes 0 to {MAX_TIMER_SECONDS} seconds, found {seconds}"
                    )));
                }
                if shared.borrow().timers.len() >= MAX_PENDING_TIMERS {
                    return Err(Error::runtime(format!(
                        "gnoblin.timers.after has {MAX_PENDING_TIMERS} timers pending; cancel some first"
                    )));
                }
                let milliseconds = (seconds * 1000.0).round() as u64;
                let due = shared.borrow().clock.saturating_add(milliseconds);
                let id = shared.borrow_mut().allocate();
                callbacks(lua)?.raw_set(id, callback)?;
                shared.borrow_mut().timers.insert(id, due);
                lua.create_userdata(Timer {
                    shared: Rc::clone(&shared),
                    timer: id,
                })
            })?,
        )?;
    }
    {
        let shared = Rc::clone(&shared);
        timers.set(
            "now",
            lua.create_function(move |_, ()| Ok(shared.borrow().clock.get() as f64 / 1000.0))?,
        )?;
    }
    gnoblin.set("timers", timers)?;

    // Core object types sit directly on `gnoblin`. The build refuses a core type named
    // like a declared member, so the two never share a key. Extension namespaces are
    // not generated here: `extension_bindings` builds them from the loaded schema.
    let mut core: Vec<&'static str> = Vec::new();
    for namespace in NAMESPACES.iter().filter(|namespace| namespace.name == "gnoblin") {
        for spec in namespace.objects {
            install_instance_meta(lua, &shared, namespace.name, spec)?;
            gnoblin.set(spec.name, install_class(lua, &shared, namespace.name, spec)?)?;
            core.push(spec.name);
        }
    }
    check_installed(&gnoblin, "gnoblin", HOST_MEMBERS, &core)?;
    let mut accepted: Vec<&'static str> = HOST_NAMES.to_vec();
    accepted.extend(core.iter().copied());

    let meta = lua.create_table()?;
    meta.set(
        "__index",
        lua.create_function(move |_, (_, key): (Table, String)| -> mlua::Result<()> {
            Err(unknown("gnoblin", &key, &accepted))
        })?,
    )?;
    meta.set(
        "__newindex",
        lua.create_function(|_, (_, _, _): (Table, Value, Value)| -> mlua::Result<()> {
            Err(Error::runtime(
                "gnoblin cannot be assigned to; every member is generated from the schema",
            ))
        })?,
    )?;
    gnoblin.set_metatable(Some(meta))?;
    lua.globals().set("gnoblin", gnoblin)?;
    Ok(())
}

/// Check an installed table against its declared members: each declared member must be
/// installed as a function or table of the declared shape, and no key may be installed
/// without a declaration. `extra` are keys that may stand beside the declared ones.
pub(crate) fn check_installed(
    table: &Table,
    path: &str,
    declared: &[HostMemberSpec],
    extra: &[&str],
) -> mlua::Result<()> {
    for member in declared {
        let key = format!("{path}.{}", member.name);
        let value: Value = table.raw_get(member.name)?;
        if member.members.is_empty() {
            if !matches!(value, Value::Function(_)) {
                return Err(Error::runtime(format!(
                    "`{key}` is declared in host_members.toml as a function, but is not installed as one"
                )));
            }
        } else {
            let Value::Table(child) = value else {
                return Err(Error::runtime(format!(
                    "`{key}` is declared in host_members.toml as a table, but is not installed as one"
                )));
            };
            check_installed(&child, &key, member.members, &[])?;
        }
    }
    for pair in table.clone().pairs::<String, Value>() {
        let (name, _) = pair?;
        let declared_here = declared.iter().any(|member| member.name == name.as_str());
        if !declared_here && !extra.contains(&name.as_str()) {
            return Err(Error::runtime(format!(
                "`{path}.{name}` is installed but not declared in host_members.toml"
            )));
        }
    }
    Ok(())
}

/// The callback registry table.
pub(super) fn callbacks(lua: &Lua) -> mlua::Result<Table> {
    lua.named_registry_value(CALLBACKS)
}

/// Drop one callback from the registry table.
///
/// `Table::raw_remove` shifts the entries above an integer key down, which would
/// move every later callback onto a different identity; assigning nil removes one
/// entry and leaves the rest alone.
pub(super) fn forget(lua: &Lua, id: u64) {
    if let Ok(callbacks) = callbacks(lua) {
        let _ = callbacks.raw_set(id, Value::Nil);
    }
}

/// The registry name of one object type's instance metatable.
fn meta_name(namespace: &str, object: &str) -> String {
    format!("gnoblin.meta.{namespace}.{object}")
}

/// The refusal for a name that is not a member.
fn unknown(owner: &str, key: &str, accepted: &[&str]) -> Error {
    let mut names = accepted.to_vec();
    names.sort_unstable();
    Error::runtime(format!("{owner} has no member `{key}`; members: {}", names.join(", ")))
}

/// Every member name an instance accepts, for a refusal.
fn members(spec: &ObjectSpec) -> Vec<&'static str> {
    let mut names: Vec<&'static str> = spec.properties.iter().map(|property| property.name).collect();
    names.extend(spec.methods.iter().map(|method| method.name));
    names.push("on");
    names
}

/// Install the class table a script reaches instances through.
fn install_class<T: Transport + 'static>(
    lua: &Lua,
    shared: &Rc<RefCell<Shared<T>>>,
    namespace: &'static str,
    spec: &'static ObjectSpec,
) -> mlua::Result<Table> {
    let class = lua.create_table()?;
    {
        let shared = Rc::clone(shared);
        class.set(
            "by_id",
            lua.create_function(move |lua, id: i64| {
                if id < 0 {
                    return Ok(Value::Nil);
                }
                let object = ObjectId::new(id as u64);
                if !holds(&shared, namespace, spec, object) {
                    return Ok(Value::Nil);
                }
                Ok(Value::Table(instance(lua, namespace, spec, object)?))
            })?,
        )?;
    }
    {
        let shared = Rc::clone(shared);
        class.set(
            "all",
            lua.create_function(move |lua, ()| {
                let ids: Vec<ObjectId> = shared
                    .borrow()
                    .mirror
                    .iter()
                    .filter(|(_, view)| view.ty().namespace() == namespace && view.ty().name() == spec.name)
                    .map(|(id, _)| *id)
                    .collect();
                let list = lua.create_table()?;
                for (position, id) in ids.into_iter().enumerate() {
                    list.raw_seti(position + 1, instance(lua, namespace, spec, id)?)?;
                }
                Ok(list)
            })?,
        )?;
    }
    let meta = lua.create_table()?;
    let owner = format!("{namespace}.{}", spec.name);
    meta.set(
        "__index",
        lua.create_function(move |_, (_, key): (Table, String)| -> mlua::Result<()> {
            Err(unknown(&owner, &key, &["all", "by_id"]))
        })?,
    )?;
    class.set_metatable(Some(meta))?;
    Ok(class)
}

/// Whether the mirror holds this object with this type.
fn holds<T: Transport>(shared: &Rc<RefCell<Shared<T>>>, namespace: &str, spec: &ObjectSpec, object: ObjectId) -> bool {
    let shared = shared.borrow();
    shared
        .mirror
        .get(&object)
        .is_some_and(|view| view.ty().namespace() == namespace && view.ty().name() == spec.name)
}

/// Install one object type's instance metatable.
fn install_instance_meta<T: Transport + 'static>(
    lua: &Lua,
    shared: &Rc<RefCell<Shared<T>>>,
    namespace: &'static str,
    spec: &'static ObjectSpec,
) -> mlua::Result<()> {
    let meta = lua.create_table()?;
    {
        let shared = Rc::clone(shared);
        meta.set(
            "__index",
            lua.create_function(move |lua, (this, key): (Table, String)| {
                index(lua, &shared, namespace, spec, &this, &key)
            })?,
        )?;
    }
    {
        let owner = format!("{namespace}.{}", spec.name);
        meta.set(
            "__newindex",
            lua.create_function(move |_, (_, key, _): (Table, String, Value)| -> mlua::Result<()> {
                Err(Error::runtime(format!(
                    "{owner}.{key} is a property and cannot be assigned; call the method that changes it"
                )))
            })?,
        )?;
    }
    {
        let owner = format!("{namespace}.{}", spec.name);
        meta.set(
            "__tostring",
            lua.create_function(move |lua, this: Table| {
                let id = identity(lua, &this)?;
                Ok(format!("{owner}({})", id.get()))
            })?,
        )?;
    }
    meta.set(
        "__eq",
        lua.create_function(|lua, (left, right): (Table, Table)| {
            Ok(identity(lua, &left).ok() == identity(lua, &right).ok())
        })?,
    )?;
    lua.set_named_registry_value(&meta_name(namespace, spec.name), meta)
}

/// The instance for one identity, created once and reused.
fn instance(lua: &Lua, namespace: &'static str, spec: &'static ObjectSpec, id: ObjectId) -> mlua::Result<Table> {
    let instances: Table = lua.named_registry_value(INSTANCES)?;
    if let Some(existing) = instances.raw_get::<Option<Table>>(id.get())? {
        return Ok(existing);
    }
    let table = lua.create_table()?;
    let meta: Table = lua.named_registry_value(&meta_name(namespace, spec.name))?;
    table.set_metatable(Some(meta))?;
    instances.raw_set(id.get(), &table)?;
    let identities: Table = lua.named_registry_value(IDENTITIES)?;
    identities.raw_set(&table, id.get())?;
    Ok(table)
}

/// The identity of an instance table.
fn identity(lua: &Lua, table: &Table) -> mlua::Result<ObjectId> {
    let identities: Table = lua.named_registry_value(IDENTITIES)?;
    let raw: Option<u64> = identities.raw_get(table)?;
    raw.map(ObjectId::new)
        .ok_or_else(|| Error::runtime("this table is not a Gnoblin object"))
}

/// Forget the instance of an object that has closed.
///
/// A closed object's identity is never reused, so the table can never be asked
/// for again; removing both registry entries keeps a session that closes many
/// windows from growing without bound.
pub(super) fn forget_instance(lua: &Lua, id: ObjectId) {
    let Ok(instances) = lua.named_registry_value::<Table>(INSTANCES) else {
        return;
    };
    let Ok(Some(table)) = instances.raw_get::<Option<Table>>(id.get()) else {
        return;
    };
    if let Ok(identities) = lua.named_registry_value::<Table>(IDENTITIES) {
        let _ = identities.raw_set(&table, Value::Nil);
    }
    let _ = instances.raw_set(id.get(), Value::Nil);
}

/// One member read: a property from the mirror, a method, or `on`.
fn index<T: Transport + 'static>(
    lua: &Lua,
    shared: &Rc<RefCell<Shared<T>>>,
    namespace: &'static str,
    spec: &'static ObjectSpec,
    this: &Table,
    key: &str,
) -> mlua::Result<Value> {
    let id = identity(lua, this)?;
    if let Some(property) = spec.properties.iter().find(|property| property.name == key) {
        let value = shared
            .borrow()
            .mirror
            .get(&id)
            .and_then(|view| view.property(property.name).cloned());
        return match value {
            Some(value) => to_lua(lua, shared, &value),
            None => Ok(Value::Nil),
        };
    }
    if let Some(method) = spec.methods.iter().find(|method| method.name == key) {
        let shared = Rc::clone(shared);
        let function = lua.create_function(move |lua, arguments: Variadic<Value>| {
            call_method(lua, &shared, spec, id, method, arguments)
        })?;
        return Ok(Value::Function(function));
    }
    if key == "on" {
        let shared = Rc::clone(shared);
        let officer = format!("{namespace}.{}", spec.name);
        let function = lua.create_function(move |lua, (_this, name, callback): (Value, String, Function)| {
            subscribe(lua, &shared, &officer, spec, id, name, callback)
        })?;
        return Ok(Value::Function(function));
    }
    Err(unknown(&format!("{namespace}.{}", spec.name), key, &members(spec)))
}

/// Call one method and return its operation handle.
fn call_method<T: Transport + 'static>(
    lua: &Lua,
    shared: &Rc<RefCell<Shared<T>>>,
    spec: &'static ObjectSpec,
    id: ObjectId,
    method: &'static MethodSpec,
    arguments: Variadic<Value>,
) -> mlua::Result<AnyUserData> {
    let mut values = Vec::from(arguments);
    // A colon call passes the object first; the function is already bound to it,
    // so the same call works written either way.
    if let Some(Value::Table(first)) = values.first()
        && identity(lua, first).is_ok_and(|found| found == id)
    {
        values.remove(0);
    }
    let mut fields = Fields::new();
    if takes_layout_reference(method) {
        // One reference argument carries the four fields the wire needs. A string is
        // refused: the module it names would not be pinned by hash.
        let [value] = values.as_slice() else {
            return Err(Error::runtime(format!(
                "{}.{} expects one layout reference after the object, found {} argument(s)",
                spec.name,
                method.name,
                values.len()
            )));
        };
        let Some((root, module, hash, options)) = layout_reference_fields(value)? else {
            return Err(Error::runtime(format!(
                "{}.{} takes a layout reference from require(), not {}",
                spec.name,
                method.name,
                value.type_name()
            )));
        };
        fields.insert("root".to_owned(), ModelValue::Text(root));
        fields.insert("module".to_owned(), ModelValue::Text(module));
        fields.insert("hash".to_owned(), ModelValue::Text(hash));
        fields.insert("options".to_owned(), ModelValue::Bytes(options));
    } else {
        if values.len() != method.params.len() {
            return Err(Error::runtime(format!(
                "{}.{} expects {} argument(s) after the object, found {}",
                spec.name,
                method.name,
                method.params.len(),
                values.len()
            )));
        }
        for (parameter, value) in method.params.iter().zip(values.iter()) {
            let label = format!("{}.{} argument `{}`", spec.name, method.name, parameter.name);
            fields.insert(
                parameter.name.to_owned(),
                convert_argument(lua, shared, parameter.ty, value, &label)?,
            );
        }
    }
    let operation = shared
        .borrow_mut()
        .call(id, method.name, &fields)
        .map_err(|error| Error::runtime(format!("{}.{}() was refused: {error}", spec.name, method.name)))?;
    lua.create_userdata(Operation {
        shared: Rc::clone(shared),
        operation,
        method: method.name,
    })
}

/// Whether a method takes a layout reference in place of its fields. Only `set_layout` on
/// `workspace` and `output` does: the Lua call names the reference once, and the wire
/// carries its `root`, `module`, `hash` and encoded `options`.
fn takes_layout_reference(method: &MethodSpec) -> bool {
    method.name == "set_layout"
        && matches!(
            method.params,
            [root, module, hash, options]
                if root.name == "root"
                    && module.name == "module"
                    && hash.name == "hash"
                    && options.name == "options"
        )
}

/// A layout reference as the `set_layout` binding reads it, before it is applied.
type LayoutReferenceFields = (String, String, String, Vec<u8>);

/// The `root`, `module`, `hash` and encoded `options` of a layout reference, or `None` when
/// the value is not one. The hash is spelled the way the reference's own `hash` field
/// spells it. The options are refused here when they are too large to encode, so an
/// oversize value fails in the configuration that made it, not on the wire.
type LayoutReferenceFields = (String, String, String, Vec<u8>);
fn layout_reference_fields(value: &Value) -> mlua::Result<Option<LayoutReferenceFields>> {
    let Value::UserData(data) = value else {
        return Ok(None);
    };
    let Ok(reference) = data.borrow::<LayoutRef>() else {
        return Ok(None);
    };
    let options = reference
        .options
        .encode()
        .map_err(|error| Error::runtime(format!("layout `{}` options: {}", reference.module, error.0)))?;
    Ok(Some((
        reference.root.to_owned(),
        reference.module.clone(),
        format!("{:016x}", reference.hash),
        options,
    )))
}

/// One Lua argument as the typed value the schema declares.
fn convert_argument<T: Transport + 'static>(
    lua: &Lua,
    shared: &Rc<RefCell<Shared<T>>>,
    ty: Ty,
    value: &Value,
    label: &str,
) -> mlua::Result<ModelValue> {
    match (ty, value) {
        (Ty::Bool, Value::Boolean(flag)) => Ok(ModelValue::Bool(*flag)),
        (Ty::Int, Value::Integer(number)) => Ok(ModelValue::Int(*number)),
        (Ty::Uint, Value::Integer(number)) if *number >= 0 => Ok(ModelValue::Uint(*number as u64)),
        (Ty::Double, Value::Integer(number)) => Ok(ModelValue::Double(*number as f64)),
        (Ty::Double, Value::Number(number)) => Ok(ModelValue::Double(*number)),
        (Ty::Text, Value::String(text)) => match text.to_str() {
            Ok(text) => Ok(ModelValue::Text(text.to_string())),
            Err(_) => Err(Error::runtime(format!("{label} expects text that is UTF-8"))),
        },
        (Ty::Bytes, Value::String(text)) => Ok(ModelValue::Bytes(text.as_bytes().to_vec())),
        (Ty::Object(name), Value::Table(table)) => {
            let object = identity(lua, table)?;
            let actual = shared
                .borrow()
                .mirror
                .get(&object)
                .map(|view| (view.ty().namespace().to_owned(), view.ty().name().to_owned()));
            match actual {
                Some((_, actual)) if actual == name => Ok(ModelValue::Object(object)),
                Some((_, actual)) => Err(Error::runtime(format!(
                    "{label} expects a {name} object, found a {actual}"
                ))),
                None => Err(Error::runtime(format!(
                    "{label} names object {} which is not live",
                    object.get()
                ))),
            }
        }
        (Ty::List(inner), Value::Table(table)) => {
            let length = table.raw_len();
            let mut items = Vec::with_capacity(length);
            for position in 1..=length {
                let item: Value = table.raw_get(position)?;
                items.push(convert_argument(
                    lua,
                    shared,
                    *inner,
                    &item,
                    &format!("{label}[{position}]"),
                )?);
            }
            Ok(ModelValue::List(items))
        }
        (ty, value) => Err(Error::runtime(format!(
            "{label} expects {}, found {}",
            ty.describe(),
            value.type_name()
        ))),
    }
}

/// Register `:on` for one signal.
fn subscribe<T: Transport + 'static>(
    lua: &Lua,
    shared: &Rc<RefCell<Shared<T>>>,
    owner: &str,
    spec: &'static ObjectSpec,
    id: ObjectId,
    name: String,
    callback: Function,
) -> mlua::Result<AnyUserData> {
    if !spec.signals.iter().any(|signal| signal.name == name) {
        let accepted: Vec<&str> = spec.signals.iter().map(|signal| signal.name).collect();
        return Err(Error::runtime(format!(
            "{owner} has no signal `{name}`; signals: {}",
            if accepted.is_empty() {
                "none".to_owned()
            } else {
                accepted.join(", ")
            }
        )));
    }
    let handler = shared.borrow_mut().allocate();
    callbacks(lua)?.raw_set(handler, callback)?;
    shared.borrow_mut().watch(
        handler,
        Watching::Signal {
            object: id,
            signal: name,
        },
    );
    lua.create_userdata(Subscription {
        shared: Rc::clone(shared),
        handler,
    })
}

/// The fields the schema declares for one signal on one live object.
///
/// The host builds a handler's argument table from this list, so a handler
/// receives the members the schema promises and nothing else. A signal the schema
/// does not declare answers `None`, which the graph cannot produce and a payload
/// from a newer compositor can.
pub(super) fn signal_fields<T: Transport>(
    shared: &Rc<RefCell<Shared<T>>>,
    object: ObjectId,
    signal: &str,
) -> Option<&'static [MemberSpec]> {
    let kind = {
        let shared = shared.borrow();
        let view = shared.mirror.get(&object)?;
        (view.ty().namespace().to_owned(), view.ty().name().to_owned())
    };
    let namespace = find_namespace(&kind.0)?;
    let spec = find_object(namespace, &kind.1)?;
    spec.signals
        .iter()
        .find(|declared| declared.name == signal)
        .map(|declared| declared.fields)
}

/// Build the argument table a signal handler receives.
pub(super) fn signal_table<T: Transport + 'static>(
    lua: &Lua,
    shared: &Rc<RefCell<Shared<T>>>,
    declared: Option<&'static [MemberSpec]>,
    fields: &Fields,
) -> mlua::Result<Table> {
    let table = lua.create_table()?;
    match declared {
        Some(declared) => {
            for member in declared {
                let value = match fields.get(member.name) {
                    Some(value) => to_lua(lua, shared, value)?,
                    None => Value::Nil,
                };
                table.set(member.name, value)?;
            }
        }
        None => {
            for (name, value) in fields {
                table.set(name.as_str(), to_lua(lua, shared, value)?)?;
            }
        }
    }
    Ok(table)
}

/// One typed value as Lua sees it.
pub(super) fn to_lua<T: Transport + 'static>(
    lua: &Lua,
    shared: &Rc<RefCell<Shared<T>>>,
    value: &ModelValue,
) -> mlua::Result<Value> {
    Ok(match value {
        ModelValue::Bool(flag) => Value::Boolean(*flag),
        ModelValue::Int(number) => Value::Integer(*number),
        ModelValue::Uint(number) => match i64::try_from(*number) {
            Ok(number) => Value::Integer(number),
            Err(_) => {
                return Err(Error::runtime(format!(
                    "the identity {number} is larger than Lua 5.5's integer, so it cannot be read"
                )));
            }
        },
        ModelValue::Double(number) => Value::Number(*number),
        ModelValue::Text(text) => Value::String(lua.create_string(text)?),
        ModelValue::Bytes(bytes) => Value::String(lua.create_string(bytes)?),
        ModelValue::Object(id) => {
            let kind = shared
                .borrow()
                .mirror
                .get(id)
                .map(|view| (view.ty().namespace().to_owned(), view.ty().name().to_owned()));
            match kind.and_then(|(namespace, name)| {
                let namespace = find_namespace(&namespace)?;
                let spec = find_object(namespace, &name)?;
                Some((namespace, spec))
            }) {
                Some((namespace, spec)) => Value::Table(instance(lua, namespace.name, spec, *id)?),
                None => Value::Nil,
            }
        }
        ModelValue::List(items) => {
            let table = lua.create_table()?;
            for (position, item) in items.iter().enumerate() {
                table.raw_seti(position + 1, to_lua(lua, shared, item)?)?;
            }
            Value::Table(table)
        }
    })
}

/// The two arguments delivered to an operation completion handler.
pub(super) fn completion_args<T: Transport + 'static>(
    lua: &Lua,
    shared: &Rc<RefCell<Shared<T>>>,
    operation: OperationId,
) -> mlua::Result<(Value, Value)> {
    let (outcome, local_error) = {
        let shared = shared.borrow();
        shared
            .operations
            .get(&operation)
            .map(|pending| (pending.outcome.clone(), pending.local_error.clone()))
            .unwrap_or((None, None))
    };
    if let Some((code, message)) = local_error {
        let error = lua.create_table()?;
        error.set("code", code)?;
        error.set("message", message)?;
        return Ok((Value::Nil, Value::Table(error)));
    }
    let value = match outcome.as_ref() {
        Some(OperationOutcome::Value(value)) => to_lua(lua, shared, value)?,
        _ => {
            let key = format!("operation-value:{}", operation.get());
            callbacks(lua)?.raw_get(key)?
        }
    };
    let error_value = match outcome {
        Some(OperationOutcome::Failed(code)) => {
            let error = lua.create_table()?;
            error.set("code", code.as_str())?;
            error.set("message", code.as_str())?;
            Value::Table(error)
        }
        _ => Value::Nil,
    };
    Ok((value, error_value))
}

/// One namespace of the generated bindings.
fn find_namespace(name: &str) -> Option<&'static NamespaceSpec> {
    NAMESPACES.iter().find(|namespace| namespace.name == name)
}

/// One object type of a namespace.
fn find_object(namespace: &'static NamespaceSpec, name: &str) -> Option<&'static ObjectSpec> {
    namespace.objects.iter().find(|object| object.name == name)
}

/// The longest delay `gnoblin.timers.after` accepts: one day, in seconds.
const MAX_TIMER_SECONDS: f64 = 86_400.0;

/// Timers that may be pending at once. A config that schedules more than this is almost
/// certainly rescheduling in a loop, so the call is refused rather than queued.
const MAX_PENDING_TIMERS: usize = 1024;

/// The `Operation` a method call returns.
///
/// One handle per call and one completion per handle is the whole contract
/// (design/rust-compositor.md, "Smaller decisions to undo"); the completion arrives
/// through the pump, once, and a second one is not delivered.
struct Operation<T: Transport> {
    shared: Rc<RefCell<Shared<T>>>,
    operation: OperationId,
    method: &'static str,
}

impl<T: Transport + 'static> UserData for Operation<T> {
    fn add_fields<F: UserDataFields<Self>>(fields: &mut F) {
        fields.add_field_method_get("id", |_, this| Ok(this.operation.get()));
        fields.add_field_method_get("method", |_, this| Ok(this.method));
        fields.add_field_method_get("status", |_, this| {
            Ok(match this.shared.borrow().status(this.operation) {
                Status::Pending => "pending",
                Status::Succeeded => "succeeded",
                Status::Failed(_) => "failed",
            })
        });
        fields.add_field_method_get("code", |_, this| Ok(this.shared.borrow().code(this.operation)));
    }

    fn add_methods<M: UserDataMethods<Self>>(methods: &mut M) {
        methods.add_method("on_complete", |lua, this, callback: Function| {
            let handler = this.shared.borrow_mut().allocate();
            callbacks(lua)?.raw_set(handler, callback)?;
            this.shared.borrow_mut().watch(
                handler,
                Watching::Completion {
                    operation: this.operation,
                },
            );
            lua.create_userdata(Subscription {
                shared: Rc::clone(&this.shared),
                handler,
            })
        });
        methods.add_method("map", |lua, this, callback: Function| {
            let target = {
                let mut shared = this.shared.borrow_mut();
                let target = shared.allocate_operation();
                shared.operations.insert(
                    target,
                    crate::host::Pending {
                        outcome: None,
                        local_error: None,
                        completions: Vec::new(),
                    },
                );
                target
            };
            let handler = this.shared.borrow_mut().allocate();
            callbacks(lua)?.raw_set(handler, callback)?;
            this.shared.borrow_mut().watch(
                handler,
                Watching::Map {
                    source: this.operation,
                    target,
                },
            );
            lua.create_userdata(Operation {
                shared: Rc::clone(&this.shared),
                operation: target,
                method: "map",
            })
        });
        methods.add_method("timeout", |lua, this, seconds: f64| {
            if !seconds.is_finite() || !(0.0..=MAX_TIMER_SECONDS).contains(&seconds) {
                return Err(Error::runtime(format!(
                    "Operation:timeout takes 0 to {MAX_TIMER_SECONDS} seconds, found {seconds}"
                )));
            }
            let mut shared = this.shared.borrow_mut();
            if shared.timers.len() >= MAX_PENDING_TIMERS {
                return Err(Error::runtime(format!(
                    "Operation:timeout has {MAX_PENDING_TIMERS} timers pending; cancel some first"
                )));
            }
            let target = shared.allocate_operation();
            shared.operations.insert(
                target,
                crate::host::Pending {
                    outcome: None,
                    local_error: None,
                    completions: Vec::new(),
                },
            );
            let milliseconds = (seconds * 1000.0).round() as u64;
            let due = shared.clock.saturating_add(milliseconds);
            let timer = shared.allocate();
            let handler = shared.allocate();
            drop(shared);
            callbacks(lua)?.raw_set(handler, lua.create_function(|_, ()| Ok(()))?)?;
            {
                let mut shared = this.shared.borrow_mut();
                shared.timers.insert(handler, due);
                shared.watch(
                    timer,
                    Watching::Forward {
                        source: this.operation,
                        target,
                        timer: handler,
                    },
                );
                shared.handlers.insert(handler, Watching::Timeout { target });
                callbacks(lua)?.raw_set(timer, lua.create_function(|_, ()| Ok(()))?)?;
            }
            lua.create_userdata(Operation {
                shared: Rc::clone(&this.shared),
                operation: target,
                method: "timeout",
            })
        });
        methods.add_method("cancel", |lua, this, ()| {
            let waiters = {
                let mut shared = this.shared.borrow_mut();
                if shared.status(this.operation) != Status::Pending {
                    return Ok(false);
                }
                let waiters: Vec<u64> = shared
                    .handlers
                    .iter()
                    .filter_map(|(id, watching)| {
                        matches!(
                            watching,
                            Watching::Map { target, .. }
                                | Watching::Forward { target, .. }
                                | Watching::Timeout { target }
                                if *target == this.operation
                        )
                        .then_some(*id)
                    })
                    .collect();
                for id in &waiters {
                    shared.handlers.remove(id);
                    shared.timers.remove(id);
                }
                for pending in shared.operations.values_mut() {
                    pending.completions.retain(|handler| !waiters.contains(handler));
                }
                let ready = shared.finish_local(
                    this.operation,
                    OperationOutcome::Done,
                    Some(("cancelled".to_owned(), "operation was cancelled".to_owned())),
                );
                shared.deferred.extend(ready);
                waiters
            };
            for id in waiters {
                forget(lua, id);
            }
            Ok(true)
        });
    }
}

/// One signal handler registration.
pub(super) struct Subscription<T: Transport> {
    pub(super) shared: Rc<RefCell<Shared<T>>>,
    pub(super) handler: u64,
}

impl<T: Transport + 'static> UserData for Subscription<T> {
    fn add_methods<M: UserDataMethods<Self>>(methods: &mut M) {
        methods.add_method("off", |lua, this, ()| {
            this.shared.borrow_mut().cancel_handler(this.handler);
            forget(lua, this.handler);
            Ok(())
        });
    }
}

/// One timer on the caller's clock.
struct Timer<T: Transport> {
    shared: Rc<RefCell<Shared<T>>>,
    timer: u64,
}

impl<T: Transport + 'static> UserData for Timer<T> {
    fn add_methods<M: UserDataMethods<Self>>(methods: &mut M) {
        methods.add_method("cancel", |lua, this, ()| {
            this.shared.borrow_mut().timers.remove(&this.timer);
            forget(lua, this.timer);
            Ok(())
        });
    }
}

#[cfg(test)]
mod tests {
    use mlua::{Lua, Table};

    use super::{HostMemberSpec, check_installed};

    const DECLARED: &[HostMemberSpec] = &[
        HostMemberSpec {
            name: "run",
            members: &[],
        },
        HostMemberSpec {
            name: "timers",
            members: &[HostMemberSpec {
                name: "now",
                members: &[],
            }],
        },
    ];

    fn load(lua: &Lua, script: &str) -> Table {
        lua.load(script).eval().expect("the test table evaluates")
    }

    #[test]
    fn a_declared_member_without_an_installer_is_refused() {
        let lua = Lua::new();
        let table = load(&lua, "return { timers = { now = function() end } }");
        let error = check_installed(&table, "gnoblin", DECLARED, &[]).expect_err("run is missing");
        assert!(error.to_string().contains("gnoblin.run"), "{error}");
    }

    #[test]
    fn an_installer_without_a_declaration_is_refused() {
        let lua = Lua::new();
        let table = load(
            &lua,
            "return { run = function() end, timers = { now = function() end }, stray = function() end }",
        );
        let error = check_installed(&table, "gnoblin", DECLARED, &[]).expect_err("stray is undeclared");
        assert!(error.to_string().contains("gnoblin.stray"), "{error}");
    }

    #[test]
    fn a_complete_table_with_core_types_beside_it_is_accepted() {
        let lua = Lua::new();
        let table = load(
            &lua,
            "return { run = function() end, timers = { now = function() end }, Window = {} }",
        );
        check_installed(&table, "gnoblin", DECLARED, &["Window"]).expect("declared plus core is accepted");
    }
}
