//! The generated Lua bindings: one table per object type, one name per member.
//!
//! Everything here is driven by the static tables `build.rs` writes into
//! `OUT_DIR` from `crates/gnoblin-schema/schema`. An object type becomes a class
//! table, a property becomes a read, a method becomes a call returning an
//! [`Operation`](OperationHandle) userdata, and a signal becomes `:on`. There is no
//! second spelling of any member (design/rust-compositor.md, "Smaller decisions to
//! undo": one generated name per member, no aliases), and an unknown name is
//! refused with the list of names that exist rather than answering `nil`.
//!
//! # The surface
//!
//! ```lua
//! local window = gnoblin.window.by_id(3)
//! print(window.title)               -- a read from the host's mirror
//! local operation = window:focus()  -- one handle, one completion
//! operation:on_complete(function() print(operation.status) end)
//! window:on("closed", function() print("gone") end)
//! ```
//!
//! The compositor's own object types sit directly on `gnoblin`, as `gnoblin.<type>`.
//! An extension namespace is loaded with `require`, which returns a module table with
//! one entry per object type: `local ext = require("example.ext")`, then
//! `ext.probe.lookup{ id = 1 }`. Those tables are built by `extension_bindings`, from the
//! schema's owned types, so they are not part of the generated surface above. `require`
//! answers only for an extension namespace the host loaded and the compositor granted;
//! any other name is an error, and a loaded namespace that was not granted is refused by name.
//!
//! # Instances
//!
//! An instance is a Lua table with one metatable per object type. Its identity is
//! kept in a registry table keyed by the instance, not as a field, so no member
//! exists that the schema does not declare. Two reads of the same object return
//! the same table, so `a == b` answers whether two records are the same object.
//!
//! A property read is a read of the host's mirror of the graph: it never reaches
//! the connection, and it reflects every observation the pump has applied.

