/// The registry table of handler and timer callbacks, keyed by identity.
///
/// Keeping the functions in the registry rather than in a Rust map is what lets the
/// host hold no Lua handle at all, so the VM and the host cannot keep each other
/// alive through a reference cycle.
pub(super) const CALLBACKS: &str = "gnoblin.callbacks";

/// The registry table of extension module tables, keyed by namespace name. The global
/// `require` reads only this table, so a script reaches nothing the catalog did not declare.
pub(super) const MODULES: &str = "gnoblin.modules";

/// The registry table of instances, keyed by object identity.
pub(super) const INSTANCES: &str = "gnoblin.instances";

/// The registry table of identities, keyed by instance.
pub(super) const IDENTITIES: &str = "gnoblin.identities";

/// The LuaCATS stub for editors, generated by `build.rs` from the same schema.
pub fn stub() -> &'static str {
    include_str!(concat!(env!("OUT_DIR"), "/gnoblin.d.lua"))
}

/// Write the stub into `dir`, answering the path it was written to.
///
/// The stub lives in `OUT_DIR` so a build never writes into the source tree; a
/// developer or a packaging script asks for a copy when an editor needs one.
pub fn write_stub(dir: &Path) -> std::io::Result<PathBuf> {
    let path = dir.join("gnoblin.d.lua");
    std::fs::write(&path, stub())?;
    Ok(path)
}

/// One schema type, as the bindings need it.
///
/// A variant the current schema does not use is still built, because the
/// generator emits it the moment a schema file declares that type: the set is the
/// schema's, not this slice's.
#[allow(dead_code)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum Ty {
    /// `bool`.
    Bool,
    /// `int`.
    Int,
    /// `uint`.
    Uint,
    /// `double`.
    Double,
    /// `string`.
    Text,
    /// `bytes`.
    Bytes,
    /// `object:<name>`, by the target type's name in the same namespace.
    Object(&'static str),
    /// `list<inner>`.
    List(&'static Ty),
}

impl Ty {
    /// How a diagnostic spells this type.
    fn describe(self) -> String {
        match self {
            Ty::Bool => "a boolean".to_owned(),
            Ty::Int => "an integer".to_owned(),
            Ty::Uint => "a non-negative integer".to_owned(),
            Ty::Double => "a number".to_owned(),
            Ty::Text => "a string".to_owned(),
            Ty::Bytes => "a string".to_owned(),
            Ty::Object(name) => format!("a {name} object"),
            Ty::List(inner) => format!("a list of {}", inner.describe()),
        }
    }
}

/// One named, typed member: a property, a method parameter or a signal field.
#[derive(Clone, Copy, Debug)]
pub(super) struct MemberSpec {
    /// The schema name.
    pub(super) name: &'static str,
    /// The schema type.
    pub(super) ty: Ty,
}

/// One method.
#[derive(Clone, Copy, Debug)]
pub(super) struct MethodSpec {
    /// The schema name.
    pub(super) name: &'static str,
    /// Its parameters, in the order a caller writes them.
    pub(super) params: &'static [MemberSpec],
}

/// One signal.
#[derive(Clone, Copy, Debug)]
pub(super) struct SignalSpec {
    /// The schema name.
    pub(super) name: &'static str,
    /// Its fields, which arrive as the callback's argument table.
    pub(super) fields: &'static [MemberSpec],
}

/// One object type.
#[derive(Clone, Copy, Debug)]
pub(super) struct ObjectSpec {
    /// The type name inside its namespace.
    pub(super) name: &'static str,
    /// Its read-only properties.
    pub(super) properties: &'static [MemberSpec],
    /// Its methods.
    pub(super) methods: &'static [MethodSpec],
    /// Its signals.
    pub(super) signals: &'static [SignalSpec],
}

/// One namespace and its object types.
#[derive(Clone, Copy, Debug)]
pub(super) struct NamespaceSpec {
    /// The namespace as the wire spells it, for example `example.ext`.
    pub(super) name: &'static str,
    /// Its object types, in schema declaration order.
    pub(super) objects: &'static [ObjectSpec],
}

/// One host-only member as `host_members.toml` declares it. A member with no `members` is
/// a function; one with children is a table.
#[derive(Clone, Copy, Debug)]
pub(crate) struct HostMemberSpec {
    /// The key on its table.
    pub(crate) name: &'static str,
    /// The children of a table; empty for a function.
    pub(crate) members: &'static [HostMemberSpec],
}

