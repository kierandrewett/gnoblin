//! What a `build.rs` calls to link `libgnoblin-core` (or `libgnoblin-std`) without building it first.
//!
//! Cargo has no artifact dependency on a `cdylib`, so a crate that links the core (an SDK crate, the launcher) cannot
//! wait for the implementation to be built. Instead it links a generated *stub*: a tiny shared object, named like the
//! core, that carries the SONAME `libgnoblin-core.so.1` and defines every export as an empty function. The link
//! records `NEEDED libgnoblin-core.so.1` and nothing else of ours; at run time the dynamic loader resolves that name to
//! the real, installed core. The stub is never installed and never run.
//!
//! A machine that has the development package can set `GNOBLIN_CORE_LIB_DIR` to the directory holding the real
//! `libgnoblin-core.so`, and the link uses that instead. `design/modular-framework.md` section 4.3 has the reasoning
//! and the measured cost (one `cc` run).
//!
//! The same mechanism links `libgnoblin-std` for the std SDK crate: [`StubSpec`] names the library, its SONAME, its
//! exports and the variable that points at a real one, and `gnoblin-std-abi` fills one in for the std library.

use std::env;
use std::fs;
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

/// The environment variable that points the link at an installed core instead of a stub.
pub const LIB_DIR_VAR: &str = "GNOBLIN_CORE_LIB_DIR";

/// Everything that names a library to link without building it: what the stub is called, what it carries as SONAME,
/// which symbols it defines, and the variable that points the link at an installed copy.
#[derive(Clone, Debug)]
pub struct StubSpec<'a> {
    /// The name the linker is told to link: `gnoblin-core` for `-lgnoblin-core`.
    pub link_name: &'a str,
    /// The SONAME the stub carries and so the name the link records as NEEDED.
    pub soname: &'a str,
    /// The symbols the stub defines, as empty functions.
    pub symbols: Vec<&'a str>,
    /// The environment variable that names a directory holding the real library.
    pub lib_dir_var: &'a str,
}

impl<'a> StubSpec<'a> {
    /// The stub of the core library, with `extra` symbols after its exports (a test launcher links a test-only export;
    /// production callers pass none).
    pub fn core(extra: &[&'a str]) -> StubSpec<'a> {
        let mut symbols: Vec<&str> = crate::export_names().collect();
        symbols.extend(extra.iter().copied());
        StubSpec {
            link_name: crate::LINK_NAME,
            soname: crate::SONAME,
            symbols,
            lib_dir_var: LIB_DIR_VAR,
        }
    }

    /// The C source of the stub: one empty function per symbol.
    pub fn source(&self) -> String {
        let mut source = format!(
            "/* generated by gnoblin-core-abi: the link stub of lib{}.so */\n",
            self.link_name
        );
        for symbol in &self.symbols {
            source.push_str("void ");
            source.push_str(symbol);
            source.push_str("(void) {}\n");
        }
        source
    }
}

/// The C source of the core's stub: one empty function per export, then one per name in `extra`.
///
/// `extra` is for a test launcher that also links a test-only export; production callers pass none.
pub fn stub_source(extra: &[&str]) -> String {
    StubSpec::core(extra).source()
}

/// The C compiler to run: `CC_<target>` when cross compiling, else `CC`, else `cc`.
fn compiler() -> String {
    let target = env::var("TARGET").unwrap_or_default();
    let host = env::var("HOST").unwrap_or_default();
    if !target.is_empty()
        && target != host
        && let Ok(compiler) = env::var(format!("CC_{}", target.replace('-', "_")))
    {
        return compiler;
    }
    env::var("CC").unwrap_or_else(|_| "cc".to_owned())
}

/// Writes the stub of `spec` into `dir` and compiles it to `dir/lib<link name>.so` with the SONAME of `spec`. Returns
/// the path of the library.
pub fn write_stub_for(dir: &Path, spec: &StubSpec<'_>) -> Result<PathBuf, String> {
    fs::create_dir_all(dir).map_err(|error| format!("cannot create {}: {error}", dir.display()))?;
    let source = dir.join(format!("{}-stub.c", spec.link_name));
    fs::write(&source, spec.source()).map_err(|error| format!("cannot write {}: {error}", source.display()))?;
    let library = dir.join(format!("lib{}.so", spec.link_name));
    let compiler = compiler();
    let status = Command::new(&compiler)
        .args(["-shared", "-fPIC"])
        .arg(format!("-Wl,-soname,{}", spec.soname))
        .arg("-o")
        .arg(&library)
        .arg(&source)
        .status()
        .map_err(|error| {
            format!(
                "cannot run the C compiler `{compiler}` to build the lib{name} link stub: {error}; \
                 install a C compiler, or set {var} to the directory that holds an installed lib{name}.so",
                name = spec.link_name,
                var = spec.lib_dir_var
            )
        })?;
    if !status.success() {
        return Err(format!(
            "`{compiler}` failed to build the lib{} link stub ({status})",
            spec.link_name
        ));
    }
    Ok(library)
}

/// Writes the core's stub into `dir` and compiles it to `dir/libgnoblin-core.so` with SONAME `libgnoblin-core.so.1`.
/// Returns the path of the library.
pub fn write_stub(dir: &Path, extra: &[&str]) -> Result<PathBuf, String> {
    write_stub_for(dir, &StubSpec::core(extra))
}

/// Emits one `cargo:` directive on stdout, which is the build-script protocol.
fn directive(line: &str) {
    // A build script that cannot write to its own stdout has no way to report it, and cargo is reading the pipe.
    let _ = writeln!(std::io::stdout().lock(), "cargo:{line}");
}

/// Links the library `spec` names into the crate being built: the installed one when the variable of `spec` names a
/// directory, otherwise a generated stub. Call it from `build.rs`; it emits the `cargo:` directives and panics with an
/// actionable message when it cannot.
pub fn link_library(spec: &StubSpec<'_>) {
    directive(&format!("rerun-if-env-changed={}", spec.lib_dir_var));
    directive("rerun-if-env-changed=CC");
    if let Some(dir) = env::var_os(spec.lib_dir_var) {
        directive(&format!("rustc-link-search=native={}", Path::new(&dir).display()));
        directive(&format!("rustc-link-lib=dylib={}", spec.link_name));
        return;
    }
    // Two stubs may be linked by one crate (the std SDK links std and core): each gets its own directory, so neither
    // overwrites the other's source or library.
    let out_dir = env::var_os("OUT_DIR")
        .map(PathBuf::from)
        .expect("OUT_DIR is not set: link_library must run in a build script");
    let dir = out_dir.join(format!("link-{}", spec.link_name));
    if let Err(message) = write_stub_for(&dir, spec) {
        panic!("{message}");
    }
    directive(&format!("rustc-link-search=native={}", dir.display()));
    directive(&format!("rustc-link-lib=dylib={}", spec.link_name));
}

/// Links the core library into the crate being built: the installed one when [`LIB_DIR_VAR`] names a directory,
/// otherwise a generated stub. Call it from `build.rs`; it emits the `cargo:` directives and panics with an actionable
/// message when it cannot.
pub fn link_core(extra: &[&str]) {
    link_library(&StubSpec::core(extra));
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_stub_defines_every_export_and_nothing_else() {
        let source = stub_source(&[]);
        for symbol in crate::export_names() {
            assert!(
                source.contains(&format!("void {symbol}(void) {{}}\n")),
                "{symbol} missing"
            );
        }
        assert_eq!(
            source.lines().filter(|line| line.starts_with("void ")).count(),
            crate::export_names().count()
        );
    }

    #[test]
    fn extra_symbols_are_appended() {
        let source = stub_source(&["gnoblin_test_main"]);
        assert!(source.contains("void gnoblin_test_main(void) {}\n"));
    }

    #[test]
    fn a_stub_of_another_library_carries_its_own_symbols_and_name() {
        let spec = StubSpec {
            link_name: "gnoblin-std",
            soname: "libgnoblin-std.so.1",
            symbols: vec!["gnoblin_std_get_api"],
            lib_dir_var: "GNOBLIN_STD_LIB_DIR",
        };
        let source = spec.source();
        assert!(source.contains("libgnoblin-std.so"), "{source}");
        assert!(source.contains("void gnoblin_std_get_api(void) {}\n"));
        assert!(!source.contains("gnoblin_get_api"));
    }
}
