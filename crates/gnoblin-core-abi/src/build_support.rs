//! What a `build.rs` calls to link `libgnoblin-core` without building it first.
//!
//! Cargo has no artifact dependency on a `cdylib`, so a crate that links the core (an SDK crate, the launcher) cannot
//! wait for the implementation to be built. Instead it links a generated *stub*: a tiny shared object, named like the
//! core, that carries the SONAME `libgnoblin-core.so.1` and defines every export as an empty function. The link
//! records `NEEDED libgnoblin-core.so.1` and nothing else of ours; at run time the dynamic loader resolves that name to
//! the real, installed core. The stub is never installed and never run.
//!
//! A machine that has the development package can set `GNOBLIN_CORE_LIB_DIR` to the directory holding the real
//! `libgnoblin-core.so`, and the link uses that instead. `design/modular-framework.md` section 4.3 has the reasoning
//! and the measured cost (one `cc` run).

use std::env;
use std::fs;
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

/// The environment variable that points the link at an installed core instead of a stub.
pub const LIB_DIR_VAR: &str = "GNOBLIN_CORE_LIB_DIR";

/// The C source of the stub: one empty function per export, then one per name in `extra`.
///
/// `extra` is for a test launcher that also links a test-only export; production callers pass none.
pub fn stub_source(extra: &[&str]) -> String {
    let mut source = String::from("/* generated by gnoblin-core-abi: the link stub of libgnoblin-core */\n");
    let mut symbols: Vec<&str> = crate::export_names().collect();
    symbols.extend(extra.iter().copied());
    for symbol in symbols {
        source.push_str("void ");
        source.push_str(symbol);
        source.push_str("(void) {}\n");
    }
    source
}

/// The C compiler to run: `CC_<target>` when cross compiling, else `CC`, else `cc`.
fn compiler() -> String {
    let target = env::var("TARGET").unwrap_or_default();
    let host = env::var("HOST").unwrap_or_default();
    if !target.is_empty()
        && target != host
        && let Ok(compiler) = env::var(format!("CC_{}", target.replace('-', "_")))
    {
        return compiler;
    }
    env::var("CC").unwrap_or_else(|_| "cc".to_owned())
}

/// Writes the stub into `dir` and compiles it to `dir/libgnoblin-core.so` with SONAME `libgnoblin-core.so.1`.
/// Returns the path of the library.
pub fn write_stub(dir: &Path, extra: &[&str]) -> Result<PathBuf, String> {
    fs::create_dir_all(dir).map_err(|error| format!("cannot create {}: {error}", dir.display()))?;
    let source = dir.join("gnoblin-core-stub.c");
    fs::write(&source, stub_source(extra)).map_err(|error| format!("cannot write {}: {error}", source.display()))?;
    let library = dir.join(format!("lib{}.so", crate::LINK_NAME));
    let compiler = compiler();
    let status = Command::new(&compiler)
        .args(["-shared", "-fPIC"])
        .arg(format!("-Wl,-soname,{}", crate::SONAME))
        .arg("-o")
        .arg(&library)
        .arg(&source)
        .status()
        .map_err(|error| {
            format!(
                "cannot run the C compiler `{compiler}` to build the libgnoblin-core link stub: {error}; \
                 install a C compiler, or set {LIB_DIR_VAR} to the directory that holds an installed libgnoblin-core.so"
            )
        })?;
    if !status.success() {
        return Err(format!(
            "`{compiler}` failed to build the libgnoblin-core link stub ({status})"
        ));
    }
    Ok(library)
}

/// Emits one `cargo:` directive on stdout, which is the build-script protocol.
fn directive(line: &str) {
    // A build script that cannot write to its own stdout has no way to report it, and cargo is reading the pipe.
    let _ = writeln!(std::io::stdout().lock(), "cargo:{line}");
}

/// Links the core library into the crate being built: the installed one when [`LIB_DIR_VAR`] names a directory,
/// otherwise a generated stub. Call it from `build.rs`; it emits the `cargo:` directives and panics with an
/// actionable message when it cannot.
pub fn link_core(extra: &[&str]) {
    directive(&format!("rerun-if-env-changed={LIB_DIR_VAR}"));
    directive("rerun-if-env-changed=CC");
    if let Some(dir) = env::var_os(LIB_DIR_VAR) {
        directive(&format!("rustc-link-search=native={}", Path::new(&dir).display()));
        directive(&format!("rustc-link-lib=dylib={}", crate::LINK_NAME));
        return;
    }
    let out_dir = env::var_os("OUT_DIR")
        .map(PathBuf::from)
        .expect("OUT_DIR is not set: link_core must run in a build script");
    if let Err(message) = write_stub(&out_dir, extra) {
        panic!("{message}");
    }
    directive(&format!("rustc-link-search=native={}", out_dir.display()));
    directive(&format!("rustc-link-lib=dylib={}", crate::LINK_NAME));
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_stub_defines_every_export_and_nothing_else() {
        let source = stub_source(&[]);
        for symbol in crate::export_names() {
            assert!(
                source.contains(&format!("void {symbol}(void) {{}}\n")),
                "{symbol} missing"
            );
        }
        assert_eq!(
            source.lines().filter(|line| line.starts_with("void ")).count(),
            crate::export_names().count()
        );
    }

    #[test]
    fn extra_symbols_are_appended() {
        let source = stub_source(&["gnoblin_test_main"]);
        assert!(source.contains("void gnoblin_test_main(void) {}\n"));
    }
}
