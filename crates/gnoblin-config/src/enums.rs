//! The enumerated settings, and the one table that maps a deprecated spelling to
//! its current one.
//!
//! Today `"normal"`, `"unlock-screen"`, `"sloppy"`, `"mouse"`, `"smart"`,
//! `"strict"`, `"lrm"` and `"lmr"` are handled in three C files and by a
//! translation pass in the Lua loader, so the same value is spelled three ways
//! depending on which file looked at it. Here an enum is parsed once, at the
//! boundary where the document is built: a value has exactly one stored spelling,
//! a deprecated spelling is accepted for one release and records a
//! [`Deprecation`], and nothing downstream ever sees the old name.
//!
//! [`ALIASES`] is that one release-long table. Removing an entry at a break is a
//! one-line change plus the test that pins it.

use std::fmt;

use crate::path::Path;

/// A setting whose values are a fixed set of names.
///
/// Implementations are generated by [`setting_enum`]; the trait exists so that a
/// generic reader can parse any of them, report the accepted values, and never
/// see a spelling that is not in the set.
pub trait SettingEnum: Copy + fmt::Debug + PartialEq + Eq {
    /// Every accepted spelling, in the order the reference lists them.
    fn variants() -> &'static [&'static str];

    /// The variant a current spelling names.
    fn from_text(text: &str) -> Option<Self>;

    /// The stored spelling of a variant.
    fn as_text(self) -> &'static str;

    /// This setting's identity, for the alias table's own test.
    fn spec() -> EnumSpec;
}

/// The identity and accepted spellings of one enumerated setting.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct EnumSpec {
    /// The document key the setting is normally stored under, or a descriptive
    /// label where several keys share the enum (`titlebar-action`).
    pub setting: &'static str,
    /// Every accepted spelling.
    pub variants: &'static [&'static str],
}

impl EnumSpec {
    /// The accepted values, spelled for a reader, including the deprecated
    /// spellings that still parse.
    pub fn expected(&self) -> String {
        let mut expected = String::from("one of ");
        for (position, variant) in self.variants.iter().enumerate() {
            if position > 0 {
                expected.push_str(", ");
            }
            expected.push_str(variant);
        }
        let deprecated: Vec<&str> = ALIASES
            .iter()
            .filter(|alias| alias.setting == self.setting)
            .map(|alias| alias.spelling)
            .collect();
        if !deprecated.is_empty() {
            expected.push_str("; deprecated spellings still accepted: ");
            for (position, spelling) in deprecated.iter().enumerate() {
                if position > 0 {
                    expected.push_str(", ");
                }
                expected.push_str(spelling);
            }
        }
        expected
    }
}

/// A deprecated spelling and the current one it stands for.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Alias {
    /// The document key the spelling is written under.
    pub setting: &'static str,
    /// The spelling that is going away.
    pub spelling: &'static str,
    /// The current spelling it means.
    pub canonical: &'static str,
}

/// Deprecated spellings, accepted until the next break.
///
/// The C loader keeps this list in `gnoblin-lua-input.c` and the value checkers
/// keep a second copy each, so a reader cannot tell which one wins. This is the
/// only copy. The `setting` is the key name because two settings can share a
/// value (`"mouse"` is a `focus-mode` and a `left-handed` spelling).
pub const ALIASES: &[Alias] = &[
    Alias {
        setting: "when",
        spelling: "normal",
        canonical: "unlocked",
    },
    Alias {
        setting: "when",
        spelling: "unlock-screen",
        canonical: "locked",
    },
    Alias {
        setting: "focus-mode",
        spelling: "sloppy",
        canonical: "hover",
    },
    Alias {
        setting: "focus-mode",
        spelling: "mouse",
        canonical: "hover-strict",
    },
    Alias {
        setting: "focus-new-windows",
        spelling: "smart",
        canonical: "allow",
    },
    Alias {
        setting: "focus-new-windows",
        spelling: "strict",
        canonical: "prevent",
    },
    Alias {
        setting: "left-handed",
        spelling: "mouse",
        canonical: "follow-mouse",
    },
    Alias {
        setting: "tap-button-map",
        spelling: "lrm",
        canonical: "left-right-middle",
    },
    Alias {
        setting: "tap-button-map",
        spelling: "lmr",
        canonical: "left-middle-right",
    },
];

/// The outcome of parsing one enum value.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EnumParse<T> {
    /// A current spelling.
    Current(T),
    /// A deprecated spelling, and the variant it means.
    Deprecated {
        /// The variant the spelling means.
        value: T,
        /// The spelling that was written.
        spelling: &'static str,
    },
    /// Not a spelling of this setting at all.
    Unsupported,
}

/// Parse `text` as `T`, accepting the deprecated spellings listed for `setting`.
pub fn parse<T: SettingEnum>(setting: &str, text: &str) -> EnumParse<T> {
    if let Some(value) = T::from_text(text) {
        return EnumParse::Current(value);
    }
    for alias in ALIASES {
        if alias.setting == setting && alias.spelling == text {
            // `ALIASES` is checked against the enums by test, so a canonical
            // spelling always parses here.
            if let Some(value) = T::from_text(alias.canonical) {
                return EnumParse::Deprecated {
                    value,
                    spelling: alias.spelling,
                };
            }
        }
    }
    EnumParse::Unsupported
}

/// A value written with a deprecated spelling, resolved to its current one.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Deprecation {
    /// Where the deprecated spelling was written.
    pub path: Path,
    /// The spelling that was written.
    pub spelling: &'static str,
    /// The spelling that replaces it.
    pub canonical: &'static str,
}

impl fmt::Display for Deprecation {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            formatter,
            "{}: deprecated spelling \"{}\"; use \"{}\"",
            self.path, self.spelling, self.canonical
        )
    }
}

/// Declare one enumerated setting.
///
/// The macro writes the variant list once and derives from it the stored
/// spelling, the parser, the accepted-values list and the [`EnumSpec`] the alias
/// test walks, so a variant cannot exist without a spelling or a spec entry.
macro_rules! setting_enum {
    (
        $(#[$meta:meta])*
        $name:ident, $setting:literal {
            $($(#[$variant_meta:meta])* $variant:ident => $text:literal),+ $(,)?
        }
    ) => {
        $(#[$meta])*
        #[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
        pub enum $name {
            $($(#[$variant_meta])* $variant,)+
        }

        impl $name {
            /// Every accepted spelling, in the order the reference lists them.
            pub const VARIANT_TEXTS: &'static [&'static str] = &[$($text),+];

            /// This setting as a spec.
            ///
            /// A constant rather than only a trait method, so [`ENUM_SPECS`] can
            /// list every enum in a `const`: a trait method cannot be called in a
            /// constant initialiser.
            pub const SPEC: EnumSpec = EnumSpec {
                setting: $setting,
                variants: Self::VARIANT_TEXTS,
            };

            /// The stored spelling of this variant.
            pub const fn as_str(self) -> &'static str {
                match self {
                    $(Self::$variant => $text,)+
                }
            }

            /// The variant a current spelling names.
            pub fn parse(text: &str) -> Option<Self> {
                match text {
                    $($text => Some(Self::$variant),)+
                    _ => None,
                }
            }
        }

        impl SettingEnum for $name {
            fn variants() -> &'static [&'static str] {
                Self::VARIANT_TEXTS
            }

            fn from_text(text: &str) -> Option<Self> {
                Self::parse(text)
            }

            fn as_text(self) -> &'static str {
                self.as_str()
            }

            fn spec() -> EnumSpec {
                Self::SPEC
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
                formatter.write_str(self.as_str())
            }
        }
    };
}

