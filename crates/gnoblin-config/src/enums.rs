#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_alias_resolves_to_a_variant_of_its_setting() {
        for alias in ALIASES {
            let specs: Vec<&EnumSpec> = ENUM_SPECS.iter().filter(|spec| spec.setting == alias.setting).collect();
            assert!(!specs.is_empty(), "alias for unknown setting {}", alias.setting);
            let mut resolved = false;
            for spec in specs {
                assert!(
                    spec.variants.contains(&alias.canonical),
                    "{} has no variant {}",
                    alias.setting,
                    alias.canonical
                );
                assert!(
                    !spec.variants.contains(&alias.spelling),
                    "{} lists the deprecated spelling {} as current",
                    alias.setting,
                    alias.spelling
                );
                resolved = true;
            }
            assert!(resolved, "alias {} -> {} has no enum", alias.spelling, alias.canonical);
        }
    }

    #[test]
    fn a_deprecated_spelling_parses_to_the_current_variant() {
        assert_eq!(
            parse::<FocusMode>("focus-mode", "sloppy"),
            EnumParse::Deprecated {
                value: FocusMode::Hover,
                spelling: "sloppy"
            }
        );
        assert_eq!(
            parse::<GestureWhen>("when", "unlock-screen"),
            EnumParse::Deprecated {
                value: GestureWhen::Locked,
                spelling: "unlock-screen"
            }
        );
    }

    #[test]
    fn a_spelling_belongs_to_its_own_setting() {
        // "mouse" is a focus-mode and a left-handed spelling, and neither leaks
        // into the other.
        assert_eq!(
            parse::<FocusMode>("focus-mode", "mouse"),
            EnumParse::Deprecated {
                value: FocusMode::HoverStrict,
                spelling: "mouse",
            }
        );
        assert_eq!(
            parse::<Handedness>("left-handed", "mouse"),
            EnumParse::Deprecated {
                value: Handedness::FollowMouse,
                spelling: "mouse",
            }
        );
        assert_eq!(
            parse::<LocationAccuracy>("max-accuracy", "mouse"),
            EnumParse::Unsupported
        );
    }

    #[test]
    fn the_expected_values_name_the_deprecated_spellings() {
        let expected = FocusMode::spec().expected();
        assert_eq!(
            expected,
            "one of click, hover, hover-strict; deprecated spellings still accepted: sloppy, mouse"
        );
        assert_eq!(Blur::spec().expected(), "one of auto, on, off");
    }
}
