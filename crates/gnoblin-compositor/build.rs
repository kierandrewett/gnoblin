//! Embed the object schema, in `OUT_DIR`.
//!
//! The compositor owns the live object graph, and the graph's vocabulary is the
//! schema: every object type, property and method it may publish is a schema
//! member. Reading `crates/gnoblin-schema/schema` at run time would tie a shipped
//! binary to a source tree it does not have, so the files are compiled in here.
//!
//! Three files come out of this script: `schema_files.rs` holds the texts,
//! `IPC_VERSION` the version the `gnoblin` namespace declares. Loading the
//! catalog here as well as at run time is deliberate: a schema the graph would
//! refuse fails the build rather than the first session start.
//!
//! The same directory is read by `gnoblin-proto`, `gnoblinctl` and `xtask`, so a
//! schema edit is one file and four rebuilds, never a checked-in copy.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use gnoblin_schema::{Catalog, Namespace};

/// The schema directory, relative to this crate.
const SCHEMA_DIR: &str = "../gnoblin-schema/schema";

/// The namespace whose version is the IPC version, which is the Gnoblin version.
const CORE_NAMESPACE: &str = "gnoblin";

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("[gnoblin-compositor] {error}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<(), String> {
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let schema_dir = manifest.join(SCHEMA_DIR);
    let out_dir = std::env::var_os("OUT_DIR")
        .map(PathBuf::from)
        .ok_or_else(|| "OUT_DIR is not set".to_owned())?;

    let files = schema_files(&schema_dir)?;
    let catalog = Catalog::load_dir(&schema_dir)
        .map_err(|error| format!("cannot load the schema in {}: {error}", schema_dir.display()))?;
    let namespace =
        Namespace::parse(CORE_NAMESPACE).map_err(|reason| format!("namespace `{CORE_NAMESPACE}`: {reason}"))?;
    let version = catalog.version(&namespace).ok_or_else(|| {
        format!("the schema declares no `{CORE_NAMESPACE}` namespace, so there is no IPC version to serve")
    })?;

    let mut rendered = String::from(
        "// Generated by crates/gnoblin-compositor/build.rs from crates/gnoblin-schema/schema/*.toml.\n\
         // Do not edit: change the schema and rebuild.\n\n\
         /// The checked-in schema files, in file-name order, as `(name, text)`.\n\
         pub const FILES: &[(&str, &str)] = &[\n",
    );
    for (name, text) in &files {
        rendered.push_str("    (");
        rendered.push_str(&format!("{name:?}"));
        rendered.push_str(", ");
        rendered.push_str(&format!("{text:?}"));
        rendered.push_str("),\n");
    }
    rendered.push_str("];\n\n");
    rendered.push_str(&format!(
        "/// The IPC version, from the schema's `{CORE_NAMESPACE}` namespace.\n\
         pub const IPC_VERSION: (u32, u32, u32) = ({}, {}, {});\n",
        version.major, version.minor, version.patch
    ));

    let path = out_dir.join("schema_files.rs");
    fs::write(&path, rendered).map_err(|error| format!("cannot write {}: {error}", path.display()))
}

/// Every `.toml` file in `dir`, in file-name order, with its text.
///
/// Order is part of the contract: `Catalog` records the load order, so a build
/// that read the directory in whatever order it came back would produce a
/// different catalog from the same tree.
fn schema_files(dir: &Path) -> Result<Vec<(String, String)>, String> {
    println!("cargo:rerun-if-changed={}", dir.display());
    let entries = fs::read_dir(dir).map_err(|error| format!("cannot read {}: {error}", dir.display()))?;
    let mut paths = Vec::new();
    for entry in entries {
        let entry = entry.map_err(|error| format!("cannot read {}: {error}", dir.display()))?;
        let path = entry.path();
        if path.extension().and_then(|extension| extension.to_str()) != Some("toml") {
            continue;
        }
        println!("cargo:rerun-if-changed={}", path.display());
        paths.push(path);
    }
    paths.sort();
    if paths.is_empty() {
        return Err(format!("no .toml schema files in {}", dir.display()));
    }
    let mut files = Vec::with_capacity(paths.len());
    for path in paths {
        let name = path
            .file_name()
            .and_then(|name| name.to_str())
            .ok_or_else(|| format!("{} is not a UTF-8 file name", path.display()))?;
        let text = fs::read_to_string(&path).map_err(|error| format!("cannot read {}: {error}", path.display()))?;
        files.push((name.to_owned(), text));
    }
    Ok(files)
}
