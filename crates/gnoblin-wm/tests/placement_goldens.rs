//! Golden table for the floating placement functions.
//!
//! `tests/shell/placement_cases.toml` (repo root) records what `placement::place` returns for the
//! inputs of its unit tests and for 200 seeded cases. The stock shell's Lua placement
//! (`data/lua/gnoblin/shell/floating.lua`) is checked against the same file.
//!
//! Regenerate with `GNOBLIN_REGEN_GOLDENS=1 cargo test -p gnoblin-wm --test placement_goldens`.
//! Without the variable the test fails when `place` no longer reproduces the committed file.

use std::fmt::Write as _;
use std::path::PathBuf;

use gnoblin_types::{Rect, Size};
use gnoblin_wm::{PlacementMode, place_new_window};

/// Fixed xorshift64 seed, so the seeded cases are the same on every run.
const SEED: u64 = 0x2545_F491_4F6C_DD1D;
const SEEDED_CASES: usize = 200;
const WORK_AREA: Rect = Rect::new(0, 0, 1920, 1080);

const HEADER: &str = "\
# Placement goldens: what `placement::place` returns for each case.
# Generated by crates/gnoblin-wm/tests/placement_goldens.rs. Regenerate with:
#   GNOBLIN_REGEN_GOLDENS=1 cargo test -p gnoblin-wm --test placement_goldens
# Rects are { x, y, w, h } in logical pixels. Modes: free_space, center, cascade.
";

struct Case {
    name: String,
    mode: PlacementMode,
    size: Size,
    area: Rect,
    occupied: Vec<Rect>,
}

fn case(name: &str, mode: PlacementMode, size: Size, area: Rect, occupied: Vec<Rect>) -> Case {
    Case {
        name: name.to_owned(),
        mode,
        size,
        area,
        occupied,
    }
}

/// The inputs of the placement unit tests. `placement_is_deterministic_and_offset_aware` makes
/// two calls, so it contributes two cases.
fn hand_cases() -> Vec<Case> {
    use PlacementMode::{Cascade, Center, FreeSpace};
    let w400 = Size::new(400, 300);
    vec![
        case("first_window_opens_at_origin", FreeSpace, w400, WORK_AREA, vec![]),
        case(
            "free_space_avoids_existing_windows",
            FreeSpace,
            w400,
            WORK_AREA,
            vec![Rect::new(0, 0, 400, 300)],
        ),
        case(
            "full_work_area_still_places_window",
            FreeSpace,
            w400,
            WORK_AREA,
            vec![WORK_AREA],
        ),
        case(
            "window_larger_than_work_area_aligns_to_it",
            FreeSpace,
            Size::new(2560, 1440),
            WORK_AREA,
            vec![],
        ),
        case("center_centres_on_work_area", Center, w400, WORK_AREA, vec![]),
        case(
            "center_cascades_when_spot_taken_exactly",
            Center,
            w400,
            WORK_AREA,
            vec![Rect::new(760, 390, 400, 300)],
        ),
        case(
            "center_stays_put_when_partially_covered",
            Center,
            w400,
            WORK_AREA,
            vec![Rect::new(760, 390, 800, 600)],
        ),
        case(
            "cascade_steps_past_placed_windows",
            Cascade,
            w400,
            WORK_AREA,
            vec![Rect::new(0, 0, 400, 300), Rect::new(32, 32, 400, 300)],
        ),
        case(
            "cascade_wraps_inside_work_area",
            Cascade,
            w400,
            WORK_AREA,
            (0..64).map(|step| Rect::new(step, step, 400, 300)).collect(),
        ),
        case(
            "offset_work_area_first_window",
            FreeSpace,
            w400,
            Rect::new(64, 32, 1856, 1000),
            vec![],
        ),
        case(
            "offset_work_area_second_window",
            FreeSpace,
            w400,
            Rect::new(64, 32, 1856, 1000),
            vec![Rect::new(64, 32, 400, 300)],
        ),
        case(
            "zero_area_raised_to_one_pixel",
            FreeSpace,
            Size::new(0, 0),
            Rect::new(0, 0, 0, 0),
            vec![],
        ),
    ]
}

/// xorshift64: the next state of the generator.
fn next(state: &mut u64) -> u64 {
    let mut x = *state;
    x ^= x << 13;
    x ^= x >> 7;
    x ^= x << 17;
    *state = x;
    x
}

/// A value in `0..n`.
fn below(state: &mut u64, n: u64) -> u64 {
    next(state) % n
}

/// A window extent: zero, oversized (past `limit`), or a normal size.
fn extent(state: &mut u64, limit: u32) -> u32 {
    match below(state, 8) {
        0 => 0,
        1 => limit + below(state, 500) as u32,
        _ => 1 + below(state, 900) as u32,
    }
}

fn seeded_cases() -> Vec<Case> {
    let mut state = SEED;
    (0..SEEDED_CASES)
        .map(|index| {
            let mode = match below(&mut state, 3) {
                0 => PlacementMode::FreeSpace,
                1 => PlacementMode::Center,
                _ => PlacementMode::Cascade,
            };
            let area = Rect::new(
                below(&mut state, 320) as i32 - 64,
                below(&mut state, 320) as i32 - 64,
                below(&mut state, 2561) as u32,
                below(&mut state, 1441) as u32,
            );
            let size = Size::new(extent(&mut state, area.width), extent(&mut state, area.height));
            let count = below(&mut state, 31);
            let mut occupied: Vec<Rect> = (0..count)
                .map(|_| {
                    Rect::new(
                        area.x - 200 + below(&mut state, u64::from(area.width) + 400) as i32,
                        area.y - 200 + below(&mut state, u64::from(area.height) + 400) as i32,
                        below(&mut state, 1001) as u32,
                        below(&mut state, 801) as u32,
                    )
                })
                .collect();
            if index % 25 == 0 {
                occupied.push(area);
            }
            if mode == PlacementMode::Center && below(&mut state, 4) == 0 {
                let x = area.x + (area.width.saturating_sub(size.width) / 2) as i32;
                let y = area.y + (area.height.saturating_sub(size.height) / 2) as i32;
                occupied.push(Rect::new(x, y, size.width, size.height));
            }
            Case {
                name: format!("seeded-{index:03}"),
                mode,
                size,
                area,
                occupied,
            }
        })
        .collect()
}

fn mode_name(mode: PlacementMode) -> &'static str {
    match mode {
        PlacementMode::FreeSpace => "free_space",
        PlacementMode::Center => "center",
        PlacementMode::Cascade => "cascade",
    }
}

fn rect(r: Rect) -> String {
    format!("{{ x = {}, y = {}, w = {}, h = {} }}", r.x, r.y, r.width, r.height)
}

fn render(cases: &[Case]) -> String {
    let mut out = String::from(HEADER);
    for case in cases {
        let result = place_new_window(case.mode, case.size, case.area, &case.occupied);
        let occupied: Vec<String> = case.occupied.iter().map(|r| rect(*r)).collect();
        let _ = write!(
            out,
            "\n[[case]]\nname = \"{}\"\nmode = \"{}\"\nsize = {{ w = {}, h = {} }}\narea = {}\noccupied = [{}]\nresult = {}\n",
            case.name,
            mode_name(case.mode),
            case.size.width,
            case.size.height,
            rect(case.area),
            occupied.join(", "),
            rect(result),
        );
    }
    out
}

fn golden_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../tests/shell/placement_cases.toml")
}

#[test]
fn placement_goldens_match_the_committed_table() {
    let mut cases = hand_cases();
    cases.extend(seeded_cases());
    let rendered = render(&cases);
    let path = golden_path();
    if std::env::var_os("GNOBLIN_REGEN_GOLDENS").is_some() {
        std::fs::create_dir_all(path.parent().expect("golden path has a parent"))
            .unwrap_or_else(|err| panic!("cannot create {}: {err}", path.display()));
        std::fs::write(&path, &rendered).unwrap_or_else(|err| panic!("cannot write {}: {err}", path.display()));
        return;
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_else(|err| {
        panic!(
            "cannot read {}: {err}; regenerate with GNOBLIN_REGEN_GOLDENS=1",
            path.display()
        )
    });
    assert!(
        committed == rendered,
        "placement::place no longer reproduces {}; if the change is intended, regenerate with GNOBLIN_REGEN_GOLDENS=1",
        path.display()
    );
}
