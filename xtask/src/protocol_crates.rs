//! `cargo xtask protocol-crates`: write the manifests of the Wayland protocol crates from one table.
//!
//! Every protocol `gnoblin-wayland` serves is a crate of its own under `crates/protocols/`, named
//! `gnoblin-wayland-<protocol>` (`design/protocol-crates.md`). Their manifests are alike, so they
//! are not written by hand: `xtask/protocols.toml` has one row per crate and one table of the
//! dependency lines a row may name, and this command writes
//!
//! - `crates/protocols/<name>/Cargo.toml` for every row, and
//! - `crates/protocols/all/Cargo.toml` and `crates/protocols/all/src/lib.rs`, the aggregate crate that
//!   `gnoblin-wayland` depends on. It re-exports each crate and holds the `ALL` table of the
//!   globals they advertise.
//!
//! The sources of a crate are written by hand. With `--check` the command fails instead of
//! writing when a generated file differs, when a directory under `crates/protocols/` has no row, or when
//! a row has no directory, so the table and the tree cannot drift.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::fs;
use std::path::Path;
use std::process::ExitCode;

use serde::Deserialize;

const TABLE: &str = "xtask/protocols.toml";
const DIRECTORY: &str = "crates/protocols";
const PREFIX: &str = "gnoblin-wayland-";
/// Directories under `crates/protocols/` that hold a hand-written crate and so have no row.
const SUPPORT: &[&str] = &["api", "all", "testkit", "types"];
/// The hand-written support crate a row may list in `needs` beside the shared crates: the plain data the compositor and the
/// protocols both name.
const TYPES: &str = "types";
const GENERATED_NOTE: &str =
    "# Generated by `cargo xtask protocol-crates` from xtask/protocols.toml. Edit the row, not this file.\n";

/// What a row describes.
#[derive(Clone, Copy, Debug, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
enum Kind {
    /// A crate that serves one protocol: it declares the interfaces it advertises.
    Protocol,
    /// A crate that serves none and holds code two protocol crates share.
    Shared,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct ProtocolRow {
    /// The crate's name without `gnoblin-wayland-`, which is also its directory under `crates/protocols/`.
    name: String,
    /// The manifest description.
    description: String,
    kind: Kind,
    /// Each advertised interface and the highest version served. Empty for a shared crate.
    #[serde(default)]
    interfaces: Vec<(String, u32)>,
    /// Whether only some sessions advertise the global (a session with no GPU renderer has no dmabuf), so the advertised-globals
    /// test checks it only when a registry lists it. Such a row is in `CONDITIONAL`, not in `ALL`.
    #[serde(default)]
    conditional: bool,
    /// Other protocol crates this one depends on, by row name. Only shared crates may be named.
    #[serde(default)]
    needs: Vec<String>,
    /// Dependency lines from the table's `[dependencies]`, by name.
    #[serde(default)]
    deps: Vec<String>,
    /// The same for `[dev-dependencies]`.
    #[serde(default, rename = "dev-deps")]
    dev_deps: Vec<String>,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct ProtocolTable {
    /// The right-hand side of each dependency line a row may name, as manifest text.
    dependencies: BTreeMap<String, String>,
    #[serde(rename = "crate")]
    crates: Vec<ProtocolRow>,
}

/// Run the command: write the generated files, or with `--check` compare them.
pub fn run(args: &[String]) -> ExitCode {
    let check = match args {
        [] => false,
        [flag] if flag == "--check" => true,
        _ => {
            eprintln!("[protocol-crates] usage: cargo xtask protocol-crates [--check]");
            return ExitCode::from(2);
        }
    };
    match execute(Path::new("."), check) {
        Ok(problems) if problems.is_empty() => {
            println!(
                "[protocol-crates] {}",
                if check {
                    "every generated file is current"
                } else {
                    "generated files written"
                }
            );
            ExitCode::SUCCESS
        }
        Ok(problems) => {
            for problem in &problems {
                println!("[protocol-crates] {problem}");
            }
            eprintln!(
                "[protocol-crates] {} problem(s); `cargo xtask protocol-crates` rewrites the files",
                problems.len()
            );
            ExitCode::FAILURE
        }
        Err(error) => {
            eprintln!("[protocol-crates] {error}");
            ExitCode::from(2)
        }
    }
}

fn execute(root: &Path, check: bool) -> Result<Vec<String>, String> {
    let table = load(root)?;
    let mut problems = validate(&table, root)?;
    let mut files = generated_files(&table);
    files.sort_by(|left, right| left.0.cmp(&right.0));
    for (relative, text) in files {
        let path = root.join(&relative);
        let current = fs::read_to_string(&path).ok();
        if current.as_deref() == Some(text.as_str()) {
            continue;
        }
        if check {
            problems.push(format!(
                "{relative} is {}",
                if current.is_some() { "stale" } else { "missing" }
            ));
        } else {
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent)
                    .map_err(|error| format!("could not create {}: {error}", parent.display()))?;
            }
            fs::write(&path, text).map_err(|error| format!("could not write {}: {error}", path.display()))?;
        }
    }
    Ok(problems)
}

fn load(root: &Path) -> Result<ProtocolTable, String> {
    let path = root.join(TABLE);
    let text = fs::read_to_string(&path).map_err(|error| format!("could not read {}: {error}", path.display()))?;
    toml::from_str(&text).map_err(|error| format!("invalid TOML in {}: {error}", path.display()))
}

/// The problems with the table itself and with how it matches the tree.
fn validate(table: &ProtocolTable, root: &Path) -> Result<Vec<String>, String> {
    let mut problems = Vec::new();
    let names: BTreeSet<&str> = table.crates.iter().map(|row| row.name.as_str()).collect();
    if names.len() != table.crates.len() {
        problems.push("two rows have the same name".to_owned());
    }
    let shared: BTreeSet<&str> = table
        .crates
        .iter()
        .filter(|row| row.kind == Kind::Shared)
        .map(|row| row.name.as_str())
        .collect();
    for row in &table.crates {
        let name = &row.name;
        if SUPPORT.contains(&name.as_str()) {
            problems.push(format!("`{name}` is the directory of a hand-written crate"));
        }
        match row.kind {
            Kind::Protocol if row.interfaces.is_empty() => {
                problems.push(format!("`{name}` serves a protocol but declares no interface"));
            }
            Kind::Shared if !row.interfaces.is_empty() => {
                problems.push(format!("`{name}` is shared code but declares interfaces"));
            }
            Kind::Shared if !name.ends_with("-shared") => {
                problems.push(format!("`{name}` is shared code, so its name ends in `-shared`: `xtask deps` finds shared crates by that suffix"));
            }
            _ => {}
        }
        for needed in &row.needs {
            if !shared.contains(needed.as_str()) && needed != TYPES {
                problems.push(format!(
                    "`{name}` needs `{needed}`, which is neither a shared crate in the table nor `{TYPES}`"
                ));
            }
        }
        for dependency in row.deps.iter().chain(&row.dev_deps) {
            if !table.dependencies.contains_key(dependency) {
                problems.push(format!(
                    "`{name}` names the dependency `{dependency}`, which `[dependencies]` does not define"
                ));
            }
        }
    }
    let directory = root.join(DIRECTORY);
    let entries =
        fs::read_dir(&directory).map_err(|error| format!("could not read {}: {error}", directory.display()))?;
    let mut on_disk = BTreeSet::new();
    for entry in entries {
        let path = entry.map_err(|error| error.to_string())?.path();
        if path.is_dir()
            && let Some(name) = path.file_name().and_then(|name| name.to_str())
        {
            on_disk.insert(name.to_owned());
        }
    }
    for name in &on_disk {
        if !names.contains(name.as_str()) && !SUPPORT.contains(&name.as_str()) {
            problems.push(format!("{DIRECTORY}/{name} has no row in {TABLE}"));
        }
    }
    for name in &names {
        if !on_disk.contains(*name) {
            problems.push(format!("the row `{name}` has no directory {DIRECTORY}/{name}"));
        }
    }
    Ok(problems)
}

/// Every generated file as (path from the root, text).
fn generated_files(table: &ProtocolTable) -> Vec<(String, String)> {
    let mut files = Vec::new();
    for row in &table.crates {
        files.push((
            format!("{DIRECTORY}/{}/Cargo.toml", row.name),
            crate_manifest(table, row),
        ));
    }
    files.push((format!("{DIRECTORY}/all/Cargo.toml"), aggregate_manifest(table)));
    files.push((format!("{DIRECTORY}/all/src/lib.rs"), aggregate_source(table)));
    files
}

fn crate_manifest(table: &ProtocolTable, row: &ProtocolRow) -> String {
    let mut text = String::from(GENERATED_NOTE);
    text.push_str("[package]\n");
    let _ = writeln!(text, "name = \"{PREFIX}{}\"", row.name);
    let _ = writeln!(text, "description = {:?}", row.description);
    text.push_str(
        "version.workspace = true\nedition.workspace = true\nrust-version.workspace = true\nlicense.workspace = true\npublish.workspace = true\n\n[lints]\nworkspace = true\n\n[dependencies]\n",
    );
    // A shared crate holds plain code two protocols use; only a protocol crate implements the api traits.
    if row.kind == Kind::Protocol {
        let _ = writeln!(text, "{PREFIX}api = {{ path = \"../api\" }}");
    }
    for needed in &row.needs {
        let _ = writeln!(text, "{PREFIX}{needed} = {{ path = \"../{needed}\" }}");
    }
    for dependency in &row.deps {
        let _ = writeln!(text, "{dependency} = {}", table.dependencies[dependency]);
    }
    if !row.dev_deps.is_empty() {
        text.push_str("\n[dev-dependencies]\n");
        for dependency in &row.dev_deps {
            let _ = writeln!(text, "{dependency} = {}", table.dependencies[dependency]);
        }
    }
    text
}

fn aggregate_manifest(table: &ProtocolTable) -> String {
    let mut text = String::from(GENERATED_NOTE);
    text.push_str("[package]\n");
    let _ = writeln!(text, "name = \"{PREFIX}protocols\"");
    text.push_str(
        "description = \"Every Wayland protocol crate of gnoblin-wayland behind one dependency, and the table of the globals they advertise.\"\nversion.workspace = true\nedition.workspace = true\nrust-version.workspace = true\nlicense.workspace = true\npublish.workspace = true\n\n[lints]\nworkspace = true\n\n[dependencies]\n",
    );
    let _ = writeln!(text, "{PREFIX}api = {{ path = \"../api\" }}");
    for row in &table.crates {
        let _ = writeln!(text, "{PREFIX}{} = {{ path = \"../{}\" }}", row.name, row.name);
    }
    text
}

fn ident(name: &str) -> String {
    name.replace('-', "_")
}

fn aggregate_source(table: &ProtocolTable) -> String {
    let mut text = String::from(
        "//! Every Wayland protocol crate of `gnoblin-wayland`, and the table of the globals they advertise.\n\
//!\n\
//! Generated by `cargo xtask protocol-crates` from `xtask/protocols.toml`. `gnoblin-wayland` depends on\n\
//! this crate alone, so adding a protocol never touches its manifest.\n\n\
use gnoblin_wayland_api::ProtocolInfo;\n\n",
    );
    // rustfmt sorts a run of `use` items, so the file is written sorted and `cargo fmt --check` leaves it alone.
    let mut names: Vec<String> = table.crates.iter().map(|row| ident(&row.name)).collect();
    names.sort();
    let prefix = ident(PREFIX);
    for name in &names {
        let _ = writeln!(text, "pub use {prefix}{name} as {name};");
    }
    text.push_str(
        "\n/// What every protocol crate advertises, in the order the table lists them. The advertised-globals test compares it with a live registry.\npub const ALL: &[&ProtocolInfo] = &[\n",
    );
    for row in table
        .crates
        .iter()
        .filter(|row| row.kind == Kind::Protocol && !row.conditional)
    {
        let _ = writeln!(text, "    &{}::PROTOCOL,", ident(&row.name));
    }
    text.push_str("];\n");
    let conditional: Vec<String> = table
        .crates
        .iter()
        .filter(|row| row.kind == Kind::Protocol && row.conditional)
        .map(|row| format!("&{}::PROTOCOL", ident(&row.name)))
        .collect();
    text.push_str(
        "\n/// What only some sessions advertise. A registry that lists one must list it at no higher version than it declares.\npub const CONDITIONAL: &[&ProtocolInfo] = &",
    );
    // rustfmt keeps an array on one line while its items take at most `array_width` (60) columns, so the file is written that way.
    let joined = conditional.join(", ");
    if joined.len() <= 60 {
        let _ = writeln!(text, "[{joined}];");
    } else {
        text.push_str("[\n");
        for item in &conditional {
            let _ = writeln!(text, "    {item},");
        }
        text.push_str("];\n");
    }
    text
}

#[cfg(test)]
mod tests {
    use super::*;

    fn table(text: &str) -> ProtocolTable {
        toml::from_str(text).expect("a table")
    }

    const SAMPLE: &str = r#"
[dependencies]
smithay = "{ workspace = true }"

[[crate]]
name = "wp-viewporter"
description = "wp_viewporter."
kind = "protocol"
interfaces = [["wp_viewporter", 1]]
deps = ["smithay"]
"#;

    #[test]
    fn a_manifest_names_the_api_crate_and_each_listed_dependency() {
        let table = table(SAMPLE);
        let manifest = crate_manifest(&table, &table.crates[0]);
        assert!(manifest.contains("name = \"gnoblin-wayland-wp-viewporter\""));
        assert!(manifest.contains("gnoblin-wayland-api = { path = \"../api\" }"));
        assert!(manifest.contains("smithay = { workspace = true }"));
        assert!(manifest.contains("[lints]\nworkspace = true"));
    }

    #[test]
    fn the_aggregate_re_exports_each_crate_and_lists_each_protocol() {
        let table = table(SAMPLE);
        let source = aggregate_source(&table);
        assert!(source.contains("pub use gnoblin_wayland_wp_viewporter as wp_viewporter;"));
        assert!(source.contains("&wp_viewporter::PROTOCOL,"));
    }

    #[test]
    fn shared_code_that_declares_an_interface_is_a_problem() {
        let mut table = table(SAMPLE);
        table.crates[0].kind = Kind::Shared;
        table.crates[0].name = "x-shared".to_owned();
        let root = std::env::temp_dir().join(format!("xtask-protocols-{}", std::process::id()));
        fs::create_dir_all(root.join(DIRECTORY).join("x-shared")).unwrap();
        let problems = validate(&table, &root).unwrap();
        fs::remove_dir_all(&root).unwrap();
        assert!(
            problems.iter().any(|problem| problem.contains("declares interfaces")),
            "{problems:?}"
        );
    }

    #[test]
    fn a_row_without_a_directory_and_a_directory_without_a_row_are_problems() {
        let table = table(SAMPLE);
        let root = std::env::temp_dir().join(format!("xtask-protocols-dirs-{}", std::process::id()));
        fs::create_dir_all(root.join(DIRECTORY).join("stray")).unwrap();
        let problems = validate(&table, &root).unwrap();
        fs::remove_dir_all(&root).unwrap();
        assert!(
            problems
                .iter()
                .any(|problem| problem.contains("`wp-viewporter` has no directory")),
            "{problems:?}"
        );
        assert!(
            problems
                .iter()
                .any(|problem| problem.contains("crates/protocols/stray has no row")),
            "{problems:?}"
        );
    }
}
