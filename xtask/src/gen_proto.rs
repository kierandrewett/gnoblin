//! `cargo xtask gen-proto`: the `.proto` files the IPC is built from.
//!
//! The schema is the source of truth and the `.proto` files are build input, so
//! they are generated, checked in and verified by CI rather than written by hand
//! (design/rust-compositor.md, "One IPC" and D16). Checking them in keeps a plain
//! `cargo build` working without running `xtask` first, and lets a reviewer see a
//! wire change in the diff of the file that causes it.
//!
//! One output file per namespace, because a Protocol Buffers package is a
//! namespace and two files with one package may not declare the same message. All
//! files that declare a namespace therefore merge into one `.proto`, in schema
//! load order, which is file-name order.
//!
//! It also writes the Rust table of members the schema marks `secret`
//! (`crates/gnoblin-proto/src/sensitive.rs`), so sensitivity is decided in one
//! place and the envelope cannot be built or decoded with the wrong flag.
//!
//! `proto/envelope.proto` is the one hand-written file there, because the envelope
//! is not a schema member; the generator leaves it alone and `build.rs` compiles it
//! with the rest.
//!
//! `--check` regenerates in memory and compares: stale, missing and orphaned files
//! all fail, so a hand edit or a forgotten regeneration is caught by `just ci`.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::io;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use gnoblin_schema::{Catalog, ErrorCode, Field, Namespace, ObjectType, Type, Version};

/// Schema files, relative to the workspace root (the `just` working directory).
const SCHEMA_DIR: &str = "crates/gnoblin-schema/schema";

/// Generated Protocol Buffers files, relative to the workspace root.
const PROTO_DIR: &str = "crates/gnoblin-proto/proto";

/// The generated Rust table of members whose frames are always sensitive.
const SENSITIVE_RS: &str = "crates/gnoblin-proto/src/sensitive.rs";

/// Files in [`PROTO_DIR`] that are written by hand and compiled with the generated
/// ones.
///
/// `envelope.proto` is the RPC envelope, which is not a schema member but the layer
/// that carries them. Everything else there comes from the schema, so anything else
/// found without a matching schema is stale.
const HAND_WRITTEN_PROTO: &[&str] = &["envelope.proto"];

/// Run the generator, or check that the checked-in files are current.
pub fn run(check: bool) -> ExitCode {
    generate_at(
        Path::new(SCHEMA_DIR),
        Path::new(PROTO_DIR),
        Path::new(SENSITIVE_RS),
        check,
    )
}

fn generate_at(schema_dir: &Path, proto_dir: &Path, sensitive_path: &Path, check: bool) -> ExitCode {
    let catalog = match Catalog::load_dir(schema_dir) {
        Ok(catalog) => catalog,
        Err(error) => {
            eprintln!("[gen-proto] {error}");
            return ExitCode::from(2);
        }
    };
    let generated = generate(&catalog, proto_dir, sensitive_path);
    if check {
        check_files(&generated, proto_dir)
    } else {
        write_files(&generated)
    }
}

/// Every generated file, path and text, in namespace order.
fn generate(catalog: &Catalog, proto_dir: &Path, sensitive_path: &Path) -> Vec<(PathBuf, String)> {
    let mut files = Vec::new();
    for namespace in catalog.namespaces() {
        let Some(version) = catalog.version(&namespace) else {
            continue;
        };
        let name = format!("{}.proto", namespace.as_str().replace('.', "_"));
        files.push((proto_dir.join(name), render(catalog, &namespace, version)));
    }
    files.push((sensitive_path.to_path_buf(), render_sensitive(catalog)));
    files
}

/// The Rust table the envelope builders and the frame decoder read.
///
/// It is generated rather than hand-kept so the `secret` flag in the schema is the
/// only place sensitivity is decided: a member marked secret is flagged on every
/// constructor and on decode, and cannot be unflagged by a caller.
fn render_sensitive(catalog: &Catalog) -> String {
    // Sorted, so the file does not move when a schema file is reordered.
    let mut members: BTreeSet<(String, String)> = BTreeSet::new();
    for namespace in catalog.namespaces() {
        for object in catalog.objects(&namespace) {
            for method in &object.methods {
                if method.is_sensitive() || object.secret {
                    members.insert((namespace.to_string(), method.name.clone()));
                }
            }
            for signal in &object.signals {
                if signal.is_sensitive() || object.secret {
                    members.insert((namespace.to_string(), signal.name.clone()));
                }
            }
        }
    }

    let mut text = String::new();
    let _ = writeln!(
        text,
        "//! Generated by `cargo xtask gen-proto` from the object schema. Do not edit:"
    );
    let _ = writeln!(text, "//! change the schema and rerun `just gen-proto`.");
    let _ = writeln!(text, "//!");
    let _ = writeln!(
        text,
        "//! Members whose frames always carry secret material. The schema marks a member,"
    );
    let _ = writeln!(
        text,
        "//! or one of its fields, `secret`; the envelope builders set `FLAG_SENSITIVE` from"
    );
    let _ = writeln!(
        text,
        "//! this table and the frame decoder re-applies it, so a secret frame is flagged"
    );
    let _ = writeln!(
        text,
        "//! whether or not the caller remembered, and a peer cannot clear the flag by"
    );
    let _ = writeln!(text, "//! sending zero.");
    let _ = writeln!(text);
    let _ = writeln!(text, "/// Every `(namespace, member)` pair the schema marks secret.");
    let _ = writeln!(text, "///");
    let _ = writeln!(
        text,
        "/// Sorted, so the generated file is stable. Layout is fixed on purpose, because"
    );
    let _ = writeln!(text, "/// this file is generated and must not be reformatted.");
    let _ = writeln!(text, "#[rustfmt::skip]");
    if members.is_empty() {
        let _ = writeln!(text, "pub(crate) const SENSITIVE_MEMBERS: &[(&str, &str)] = &[];");
    } else {
        let _ = writeln!(text, "pub(crate) const SENSITIVE_MEMBERS: &[(&str, &str)] = &[");
        for (namespace, member) in &members {
            let _ = writeln!(text, "    (\"{namespace}\", \"{member}\"),");
        }
        let _ = writeln!(text, "];");
    }
    let _ = writeln!(text);
    let _ = writeln!(
        text,
        "/// Whether every frame for this namespace and member is sensitive."
    );
    let _ = writeln!(
        text,
        "pub(crate) fn is_sensitive(namespace: &str, member: &str) -> bool {{"
    );
    let _ = writeln!(text, "    SENSITIVE_MEMBERS.contains(&(namespace, member))");
    let _ = writeln!(text, "}}");
    text
}

/// The text of one namespace's `.proto` file.
fn render(catalog: &Catalog, namespace: &Namespace, version: Version) -> String {
    let mut text = String::new();
    let _ = writeln!(
        text,
        "// Generated by `cargo xtask gen-proto` from the object schema. Do not"
    );
    let _ = writeln!(text, "// edit: change the schema and rerun `just gen-proto`.");
    let _ = writeln!(text, "//");
    let _ = writeln!(text, "// Namespace: {namespace}");
    let _ = writeln!(text, "// Version: {version}");
    // File names, not the path they were loaded through, so the checked-in text
    // does not depend on how the generator was invoked.
    let origins: Vec<String> = catalog
        .origins(namespace)
        .map(|origin| {
            Path::new(origin)
                .file_name()
                .map_or_else(|| origin.to_owned(), |name| name.to_string_lossy().into_owned())
        })
        .collect();
    let _ = writeln!(text, "// Schema: {SCHEMA_DIR} ({})", origins.join(", "));
    let _ = writeln!(text);
    let _ = writeln!(text, "syntax = \"proto3\";");
    let _ = writeln!(text);
    let _ = writeln!(text, "package {namespace};");

    for object in catalog.objects(namespace) {
        let _ = writeln!(text);
        render_object(&mut text, object);
    }

    let errors: Vec<&ErrorCode> = catalog.errors(namespace).collect();
    if !errors.is_empty() {
        let _ = writeln!(text);
        render_errors(&mut text, namespace, &errors);
    }
    text
}

fn render_object(text: &mut String, object: &ObjectType) {
    let secret = if object.secret { ", secret" } else { "" };
    let _ = writeln!(text, "// Object `{}`, since {}{secret}.", object.name, object.since);
    let _ = writeln!(text, "message {} {{", to_upper_camel(&object.name));

    if object.properties.is_empty() {
        let _ = writeln!(text, "  message Properties {{}}");
    } else {
        let _ = writeln!(
            text,
            "  // Property values, carried by a property diff. Field numbers never change."
        );
        let _ = writeln!(text, "  message Properties {{");
        for (index, property) in object.properties.iter().enumerate() {
            let mut notes = vec![format!("since {}", property.since)];
            if property.secret {
                notes.push(SECRET_NOTE.to_owned());
            }
            render_field(text, "    ", &property.name, index + 1, &property.ty, &notes);
        }
        let _ = writeln!(text, "  }}");
    }

    for method in &object.methods {
        let secret = if method.secret { ", secret" } else { "" };
        let _ = writeln!(text);
        let _ = writeln!(text, "  // Method `{}`, since {}{secret}.", method.name, method.since);
        let name = format!("{}Args", to_upper_camel(&method.name));
        render_message(text, &name, &method.params, "  ");
    }

    for signal in &object.signals {
        let secret = if signal.secret { ", secret" } else { "" };
        let _ = writeln!(text);
        let _ = writeln!(text, "  // Signal `{}`, since {}{secret}.", signal.name, signal.since);
        let name = format!("{}Payload", to_upper_camel(&signal.name));
        render_message(text, &name, &signal.fields, "  ");
    }

    let _ = writeln!(text, "}}");
}

/// Render a nested message with `fields`, or an empty one on a single line.
fn render_message(text: &mut String, name: &str, fields: &[Field], indent: &str) {
    if fields.is_empty() {
        let _ = writeln!(text, "{indent}message {name} {{}}");
        return;
    }
    let _ = writeln!(text, "{indent}message {name} {{");
    let field_indent = format!("{indent}  ");
    for (index, field) in fields.iter().enumerate() {
        let mut notes = vec![format!("since {}", field.since)];
        if field.secret {
            notes.push(SECRET_NOTE.to_owned());
        }
        render_field(text, &field_indent, &field.name, index + 1, &field.ty, &notes);
    }
    let _ = writeln!(text, "{indent}}}");
}

fn render_field(text: &mut String, indent: &str, name: &str, tag: usize, ty: &Type, notes: &[String]) {
    let (label, proto_type, note) = proto_type(ty);
    let mut notes = notes.to_vec();
    if let Some(note) = note {
        notes.push(note);
    }
    let _ = writeln!(text, "{indent}// {}", notes.join("; "));
    match label {
        Some(label) => {
            let _ = writeln!(text, "{indent}{label} {proto_type} {name} = {tag};");
        }
        None => {
            let _ = writeln!(text, "{indent}{proto_type} {name} = {tag};");
        }
    }
}

const SECRET_NOTE: &str = "secret: every frame carrying this field is flagged sensitive";

/// The Protocol Buffers label, type and extra note for a schema type.
fn proto_type(ty: &Type) -> (Option<&'static str>, String, Option<String>) {
    match ty {
        Type::Bool => (None, "bool".to_owned(), None),
        Type::Int => (None, "int64".to_owned(), None),
        Type::Uint => (None, "uint64".to_owned(), None),
        Type::Double => (None, "double".to_owned(), None),
        Type::Text => (None, "string".to_owned(), None),
        Type::Bytes => (None, "bytes".to_owned(), None),
        // An object identity is a string here: the wire carries the id and the
        // schema carries the type, so a reader without the schema still knows it
        // is an identity rather than a title.
        Type::ObjectRef(name) => (None, "string".to_owned(), Some(format!("object id of `{name}`"))),
        Type::List(inner) => {
            let (_, proto_type, note) = proto_type(inner);
            (
                Some("repeated"),
                proto_type,
                Some(note.map_or_else(|| "list".to_owned(), |note| format!("list of {note}"))),
            )
        }
    }
}

fn render_errors(text: &mut String, namespace: &Namespace, errors: &[&ErrorCode]) {
    let prefix = namespace
        .as_str()
        .split('.')
        .map(to_upper_snake)
        .collect::<Vec<String>>()
        .join("_");
    let name = namespace
        .as_str()
        .split('.')
        .map(to_upper_camel)
        .collect::<Vec<String>>()
        .concat();
    let _ = writeln!(
        text,
        "// Error codes `{namespace}` returns, in the envelope's error frame."
    );
    let _ = writeln!(
        text,
        "// The wire carries the code as text, so a peer reports one it does not know."
    );
    let _ = writeln!(text, "enum {name}Error {{");
    let _ = writeln!(text, "  {prefix}_UNSPECIFIED = 0;");
    for (index, error) in errors.iter().enumerate() {
        let _ = writeln!(text, "  // since {}", error.since);
        let _ = writeln!(
            text,
            "  {prefix}_{} = {};",
            error.name.to_uppercase().replace('-', "_"),
            index + 1
        );
    }
    let _ = writeln!(text, "}}");
}

fn to_upper_camel(text: &str) -> String {
    text.split(['_', '-'])
        .map(|word| {
            let mut characters = word.chars();
            match characters.next() {
                Some(first) => first.to_ascii_uppercase().to_string() + characters.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

fn to_upper_snake(text: &str) -> String {
    text.to_uppercase().replace('-', "_")
}

fn write_files(generated: &[(PathBuf, String)]) -> ExitCode {
    for (path, text) in generated {
        if let Some(dir) = path.parent()
            && let Err(error) = std::fs::create_dir_all(dir)
        {
            eprintln!("[gen-proto] cannot create {}: {error}", dir.display());
            return ExitCode::from(2);
        }
        if let Err(error) = std::fs::write(path, text) {
            eprintln!("[gen-proto] cannot write {}: {error}", path.display());
            return ExitCode::from(2);
        }
        println!("[gen-proto] wrote {}", path.display());
    }
    ExitCode::SUCCESS
}

/// Files that are stale, missing or orphaned, or an I/O error while looking.
///
/// Separate from the exit code so tests can assert on the findings themselves.
fn stale_files(generated: &[(PathBuf, String)], proto_dir: &Path) -> io::Result<Vec<String>> {
    let mut stale = Vec::new();
    for (path, text) in generated {
        match std::fs::read_to_string(path) {
            Ok(existing) if existing == *text => {}
            Ok(_) => stale.push(format!("{} is out of date", path.display())),
            Err(error) if error.kind() == io::ErrorKind::NotFound => {
                stale.push(format!("{} is missing", path.display()));
            }
            Err(error) => return Err(error),
        }
    }
    // A file nothing generates is as wrong as a stale one: it would be compiled
    // into a client while no schema describes it.
    match std::fs::read_dir(proto_dir) {
        Ok(entries) => {
            for entry in entries.flatten() {
                let path = entry.path();
                if path.extension().and_then(|extension| extension.to_str()) != Some("proto") {
                    continue;
                }
                if hand_written(&path) {
                    continue;
                }
                if !generated.iter().any(|(generated, _)| generated == &path) {
                    stale.push(format!("{} is not generated from any schema", path.display()));
                }
            }
        }
        Err(error) if error.kind() == io::ErrorKind::NotFound => {
            if !generated.is_empty() {
                stale.push(format!("{} does not exist", proto_dir.display()));
            }
        }
        Err(error) => return Err(error),
    }
    Ok(stale)
}

/// Whether a file in the proto directory is one we write by hand.
fn hand_written(path: &Path) -> bool {
    path.file_name()
        .and_then(|name| name.to_str())
        .is_some_and(|name| HAND_WRITTEN_PROTO.contains(&name))
}

fn check_files(generated: &[(PathBuf, String)], proto_dir: &Path) -> ExitCode {
    let stale = match stale_files(generated, proto_dir) {
        Ok(stale) => stale,
        Err(error) => {
            eprintln!("[gen-proto] cannot read {}: {error}", proto_dir.display());
            return ExitCode::from(2);
        }
    };
    if stale.is_empty() {
        println!("[gen-proto] {} file(s) up to date", generated.len());
        return ExitCode::SUCCESS;
    }
    for line in &stale {
        println!("[gen-proto] {line}");
    }
    eprintln!("[gen-proto] the generated .proto files are stale: run `just gen-proto` and commit the result");
    ExitCode::FAILURE
}

#[cfg(test)]
mod tests {
    use std::path::{Path, PathBuf};
    use std::process::ExitCode;

    use super::{check_files, generate, render, render_sensitive, stale_files, write_files};
    use gnoblin_schema::Catalog;

    fn workspace(path: &str) -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("..").join(path)
    }

    fn catalog() -> Catalog {
        Catalog::load_dir(&workspace("crates/gnoblin-schema/schema")).expect("schema")
    }

    #[test]
    fn one_file_per_namespace_plus_the_sensitive_table() {
        let generated = generate(&catalog(), Path::new("out"), Path::new("sensitive.rs"));
        let names: Vec<String> = generated
            .iter()
            .map(|(path, _)| path.file_name().expect("name").to_string_lossy().to_string())
            .collect();
        assert_eq!(
            names,
            vec![
                "bsm_greeter.proto".to_owned(),
                "gnoblin.proto".to_owned(),
                "sensitive.rs".to_owned()
            ]
        );
    }

    #[test]
    fn the_sensitive_table_names_every_secret_member() {
        let text = render_sensitive(&catalog());
        assert!(text.contains("(\"bsm.greeter\", \"auth_response\")"), "{text}");
        // A member with no secret field is not listed.
        assert!(!text.contains("\"begin_auth\""), "{text}");
        assert!(!text.contains("\"focus\""), "{text}");
        assert!(text.contains("#[rustfmt::skip]"), "{text}");
    }

    #[test]
    fn renders_objects_methods_signals_and_errors() {
        let catalog = catalog();
        let namespaces = catalog.namespaces();
        let gnoblin = namespaces
            .iter()
            .find(|namespace| namespace.as_str() == "gnoblin")
            .expect("gnoblin");
        let text = render(&catalog, gnoblin, catalog.version(gnoblin).expect("version"));

        assert!(text.contains("package gnoblin;"), "{text}");
        assert!(text.contains("message Session {"), "{text}");
        assert!(text.contains("string version = 1;"), "{text}");
        assert!(text.contains("message ReadyPayload {}"), "{text}");
        assert!(text.contains("message Window {"), "{text}");
        assert!(text.contains("uint64 id = 1;"), "{text}");
        assert!(text.contains("message FocusArgs {}"), "{text}");
        assert!(text.contains("message ClosedPayload {}"), "{text}");
        assert!(text.contains("enum GnoblinError {"), "{text}");
        assert!(text.contains("GNOBLIN_UNKNOWN_MEMBER = 1;"), "{text}");
    }

    #[test]
    fn marks_a_secret_field_and_names_an_object_reference() {
        let catalog = catalog();
        let namespaces = catalog.namespaces();
        let greeter = namespaces
            .iter()
            .find(|namespace| namespace.as_str() == "bsm.greeter")
            .expect("greeter");
        let text = render(&catalog, greeter, catalog.version(greeter).expect("version"));

        assert!(text.contains("package bsm.greeter;"), "{text}");
        assert!(text.contains("message BeginAuthArgs {"), "{text}");
        assert!(text.contains("string user = 1;"), "{text}");
        assert!(
            text.contains("string response = 1;") && text.contains("secret: every frame"),
            "{text}"
        );
        assert!(text.contains("message PromptPayload {"), "{text}");
        assert!(text.contains("BSM_GREETER_PROVIDER_GONE = 1;"), "{text}");
    }

    #[test]
    fn the_checked_in_files_are_current() {
        // The same comparison `just ci` makes, as a unit test: a hand edit of a
        // .proto file or of the sensitive table fails wherever the suite runs.
        let proto_dir = workspace("crates/gnoblin-proto/proto");
        let generated = generate(
            &catalog(),
            &proto_dir,
            &workspace("crates/gnoblin-proto/src/sensitive.rs"),
        );
        assert_eq!(
            check_files(&generated, &proto_dir),
            ExitCode::SUCCESS,
            "run `just gen-proto`"
        );
    }

    #[test]
    fn reports_a_stale_and_an_orphaned_file() {
        let dir = std::env::temp_dir().join(format!("gnoblin-gen-proto-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        let proto_dir = dir.join("proto");
        std::fs::create_dir_all(&proto_dir).expect("temp dir");
        let generated = generate(&catalog(), &proto_dir, &dir.join("sensitive.rs"));
        let _ = write_files(&generated);
        assert!(
            stale_files(&generated, &proto_dir).expect("scan").is_empty(),
            "a fresh write is current"
        );

        let first = &generated[0].0;
        std::fs::write(first, "// hand edited\n").expect("write");
        let stale = stale_files(&generated, &proto_dir).expect("scan");
        assert!(
            stale.iter().any(|problem| problem.contains("is out of date")),
            "{stale:?}"
        );

        std::fs::write(proto_dir.join("orphan.proto"), "").expect("write");
        let stale = stale_files(&generated, &proto_dir).expect("scan");
        assert!(
            stale.iter().any(|problem| problem.contains("orphan.proto")),
            "{stale:?}"
        );

        // The hand-written envelope is not an orphan: it is compiled, and the
        // generator must leave it alone.
        std::fs::write(proto_dir.join("envelope.proto"), "// hand written\n").expect("write");
        let stale = stale_files(&generated, &proto_dir).expect("scan");
        assert!(
            !stale.iter().any(|problem| problem.contains("envelope.proto")),
            "{stale:?}"
        );
        std::fs::remove_dir_all(&dir).expect("clean up");
    }
}
